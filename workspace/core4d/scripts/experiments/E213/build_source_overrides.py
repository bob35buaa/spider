#!/usr/bin/env python3
"""E213 Phase A step 2: write + audit one Hydra override per (case, aug variant).

Each override inherits E208's PRG override for that aug task verbatim and changes
exactly one key -- ``scene_name`` -> the selected-arm gravcomp sidecar.  This is
E212's pattern (inherit the PRG config, swap only the scene) applied to the aug
tasks: the E208 PRG override already expands the full PRG payload (leg gate,
reward, contact mask), so the only thing E213 changes is which object-gravcomp
scene CEM loads.

The audit composes both the E208-PRG override and the E213 candidate through
Hydra and requires the resolved symmetric difference to be exactly
{"scene_name"} -- proving the arm swap is single-variable at the config level.

PRG-selected cases are skipped (their arm IS the E208 PRG override).

Usage:
    .venv/bin/python workspace/core4d/scripts/experiments/E213/build_source_overrides.py
    ... --no-audit --limit N --cases <id,...>
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

import e213_common as C  # noqa: E402

HEADER = "# @package _global_\n# Auto-generated by E213/build_source_overrides.py.\n"
ALLOWED_DIFF = {"scene_name"}


def write_override(case: dict[str, str], aug_row: dict[str, str]) -> Path:
    case_id, variant, arm = case["case_id"], aug_row["aug_variant"], case["arm"]
    base_id = C.e208_prg_override_id(case_id, variant)
    body = (
        f"{HEADER}"
        f"# E213 selected arm {arm} (g={C.selected_gravcomp_str(case)}) on E208 aug task "
        f"{aug_row['target_task']}.\n"
        "# Single variable vs the E208 PRG aug override: scene_name -> selected gravcomp sidecar.\n"
        "defaults:\n"
        f"- {base_id}\n"
        "- _self_\n"
        f"scene_name: {case['arm_scene_name']}\n"
    )
    path = C.override_path(case_id, variant, arm)
    path.write_text(body, encoding="utf-8")
    return path


def _compose(override_id: str) -> dict[str, Any]:
    from hydra import compose, initialize_config_dir
    from omegaconf import OmegaConf

    config_dir = str((C.REPO / "examples/config").resolve())
    with initialize_config_dir(version_base=None, config_dir=config_dir):
        cfg = compose(config_name="default", overrides=[f"+override={override_id}"])
    out = OmegaConf.to_container(cfg, resolve=True)
    assert isinstance(out, dict)
    return out


def _drift(a: dict[str, Any], b: dict[str, Any]) -> set[str]:
    return {k for k in set(a) | set(b) if a.get(k, "\0missing") != b.get(k, "\0missing")}


def audit_one(case: dict[str, str], aug_row: dict[str, str]) -> list[str]:
    case_id, variant, arm = case["case_id"], aug_row["aug_variant"], case["arm"]
    base = _compose(C.e208_prg_override_id(case_id, variant))
    cand = _compose(C.override_id(case_id, variant, arm))
    fails: list[str] = []
    unexpected = _drift(base, cand) - ALLOWED_DIFF
    if unexpected:
        fails.append("non_axis_drift:" + ",".join(
            f"{k}({base.get(k)}->{cand.get(k)})" for k in sorted(unexpected)))
    if "scene_name" not in _drift(base, cand):
        fails.append("scene_name did not change vs E208 PRG")
    if cand.get("scene_name") != case["arm_scene_name"]:
        fails.append(f"scene_name={cand.get('scene_name')}!={case['arm_scene_name']}")
    return fails


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--audit", action="store_true", default=True)
    ap.add_argument("--no-audit", dest="audit", action="store_false")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--cases", default="")
    args = ap.parse_args()

    cases = {c["case_id"]: c for c in C.load_cases()}
    if args.cases:
        keep = {c.strip() for c in args.cases.split(",") if c.strip()}
        cases = {k: v for k, v in cases.items() if k in keep}
    aug = C.aug_rows_by_case()

    work: list[tuple[dict[str, str], dict[str, str]]] = []
    for case_id in sorted(cases):
        case = cases[case_id]
        if C.is_prg_case(case):
            continue
        for row in aug.get(case_id, []):
            work.append((case, row))
    if args.limit:
        work = work[: args.limit]

    for case, row in work:
        # the inherited E208 PRG override must exist or the chain is dangling
        base_yaml = C.OVERRIDE_DIR / f"{C.e208_prg_override_id(case['case_id'], row['aug_variant'])}.yaml"
        if not base_yaml.is_file():
            raise SystemExit(f"missing E208 PRG override to inherit: {base_yaml}")
        write_override(case, row)
    print(f"wrote {len(work)} override YAMLs to {C.OVERRIDE_DIR.relative_to(C.REPO)}")

    if not args.audit:
        return 0
    failures: dict[str, list[str]] = {}
    audit_rows: list[dict[str, Any]] = []
    for case, row in work:
        fails = audit_one(case, row)
        key = f"{case['case_id']}/{row['aug_variant']}/{case['arm']}"
        audit_rows.append({"key": key, "fails": fails})
        if fails:
            failures[key] = fails
    C.write_json(C.OVERRIDE_AUDIT_JSON, {
        "n": len(work), "n_failures": len(failures), "allowed_diff": sorted(ALLOWED_DIFF),
        "failures": failures, "updated_at": C.now(),
    })
    if failures:
        for key, fails in failures.items():
            print(f"  FAIL {key}: {'; '.join(fails)}")
        raise SystemExit(f"C2 override audit FAILED for {len(failures)} rows")
    print(f"C2 PASS: {len(work)} overrides differ from their E208 PRG parent by exactly "
          f"{sorted(ALLOWED_DIFF)} -> {C.rel(C.OVERRIDE_AUDIT_JSON)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
