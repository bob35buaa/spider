#!/usr/bin/env python3
"""Build E189 E167A rubber-hull scenes, overrides and CEM manifests.

The exact 43 paired inputs (box004 from E172, box024/box001 from E173) are
inherited from ``input_authority.tsv``.  For each row this script:

1. starts from the restored pristine ``scene_act.xml``;
2. runs the shared rubber-hull hand patch to create a fresh
   ``scene_act_E189_rubberHull.xml``;
3. writes an override that inherits the existing dcv3/E167A override and
   changes only ``scene_name``;
4. proves E167A parity and the absence of E170 PRG config/scene additions;
5. emits the frozen 9-row canary and 43-row Full manifests, sharded across
   the eight local GPUs.
"""

