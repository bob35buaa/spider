def dry_run_summary(rows: list[dict[str, str]]) -> dict[str, Any]:
    failures = []
    for row in rows:
        for key in (
            "source_scene",
            "trimmed_npz",
            "target_scene",
            "trajectory",
            "base_scene_act",
            "pristine_scene_snapshot",
            "contact_mask",
            "dcv3_override_path",
        ):
            if not C.repo_path(row[key]).is_file():
                failures.append(f"{row['case_id']}:missing:{key}")
        if (
            C.repo_path(row["trajectory"]).is_file()
            and C.sha256(row["trajectory"]) != row["trajectory_sha256"]
        ):
            failures.append(f"{row['case_id']}:trajectory_sha_mismatch")
    return {
        "created_at": C.now(),
        "mode": "dry_run",
        "authority_rows": len(rows),
        "unique_rows": len({row["case_id"] for row in rows}),
        "canary_rows": sum(C.boolish(row["canary_selected"]) for row in rows),
        "worker_distribution": dict(Counter(row["worker"] for row in rows)),
        "failures": failures,
        "status": "pass" if not failures else "fail",
    }


def apply(rows: list[dict[str, str]], *, snapshot: bool) -> dict[str, Any]:
    profile_doc = json.loads(C.E167A_PROFILE.read_text(encoding="utf-8"))
    if profile_doc["profile_sha256"] != C.EXPECTED_E167A_PROFILE_SHA256:
        raise ValueError("E167A profile SHA drift")
    expected_profile = dict(profile_doc["profile"])
    expected_profile["cem_smooth_enabled"] = False
    scene_rows = []
    config_rows = []
    full_rows = []
    canary_rows = []
    for source in rows:
        scene = build_scene(source, snapshot=snapshot)
        override_path = write_override(source)
        config = audit_override(source, override_path, expected_profile)
        scene_rows.append(scene)
        config_rows.append(config)
        if scene["scene_audit_status"] != "pass":
            raise ValueError(
                f"scene audit failed: {source['case_id']} {scene['failures']}"
            )
        if config["audit_status"] != "pass":
            raise ValueError(
                f"config audit failed: {source['case_id']} {config['failures']}"
            )
        full_rows.append(manifest_row(source, scene, config, stage="full"))
        if C.boolish(source["canary_selected"]):
            canary_rows.append(manifest_row(source, scene, config, stage="canary"))

    if len(full_rows) != C.EXPECTED_PAIRED_ROWS or len(canary_rows) != len(
        C.CANARY_CASES
    ):
        raise ValueError(
            f"manifest row drift: full={len(full_rows)} canary={len(canary_rows)}"
        )
    manifests = C.RESULTS / "s6_downstream/manifests"
    C.write_tsv(manifests / "cem_full_manifest.tsv", full_rows)
    C.write_tsv(manifests / "cem_canary_manifest.tsv", canary_rows)
    workers = sorted({row["assigned_worker"] for row in full_rows})
    for worker in workers:
        slug = worker.replace("-", "_")
        worker_rows = [row for row in full_rows if row["assigned_worker"] == worker]
        C.write_tsv(manifests / f"cem_full_{slug}.tsv", worker_rows)
    audit_dir = C.RESULTS / "s5_handoff/config_scene_audit"
    C.write_tsv(audit_dir / "scene_audit.tsv", scene_rows)
    C.write_tsv(audit_dir / "config_audit.tsv", config_rows)
    C.write_json(audit_dir / "scene_audit.json", scene_rows)
    C.write_json(audit_dir / "config_audit.json", config_rows)
    summary = {
        "created_at": C.now(),
        "status": "pass",
        "authority_rows": len(rows),
        "full_rows": len(full_rows),
        "canary_rows": len(canary_rows),
        "scene_audit_pass": sum(
            row["scene_audit_status"] == "pass" for row in scene_rows
        ),
        "config_audit_pass": sum(
            row["audit_status"] == "pass" for row in config_rows
        ),
        "no_prg_pair_pass": sum(
            int(row["lowerbody_object_pair_count"]) == 0 for row in scene_rows
        ),
        "source_preprg_rubber_semantic_exact": sum(
            C.boolish(row["source_preprg_semantic_exact"]) for row in scene_rows
        ),
        "e167a_profile_sha256": profile_doc["profile_sha256"],
        "scene_name": C.SCENE_NAME,
        "worker_distribution": dict(
            Counter(row["assigned_worker"] for row in full_rows)
        ),
        "worker_shards": {
            worker: C.rel(manifests / f"cem_full_{worker.replace('-', '_')}.tsv")
            for worker in workers
        },
        "full_budget": {
            "seed": C.CEM_SEED,
            "samples": C.CEM_FULL_SAMPLES,
            "opt_steps": C.CEM_FULL_OPT_STEPS,
        },
        "snapshot_written": snapshot,
    }
    C.write_json(manifests / "cem_manifest_summary.json", summary)
    return summary


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--dry-run", action="store_true")
    mode.add_argument("--apply", action="store_true")
    parser.add_argument("--snapshot", action="store_true")
    args = parser.parse_args()
    authority_path = C.RESULTS / "input_authority/input_authority.tsv"
    if not authority_path.is_file():
        raise FileNotFoundError(f"build paired authority first: {authority_path}")
    rows = C.read_tsv(authority_path)
    gpu_queues = C.compute_gpu_queues([row["case_id"] for row in rows])
    C.validate_queue_contract({row["case_id"] for row in rows}, gpu_queues)
    summary = (
        dry_run_summary(rows) if args.dry_run else apply(rows, snapshot=args.snapshot)
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0 if summary["status"] == "pass" else 1


if __name__ == "__main__":
    raise SystemExit(main())
