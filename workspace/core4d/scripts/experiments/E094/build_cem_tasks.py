#!/usr/bin/env python3
"""Build E094 CEM variants using adaptive-support external targets."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Any


REPO = Path(__file__).resolve().parents[4]
OVERRIDE_ROOT = REPO / "examples/config/override"
E092_VARIANTS = REPO / "workspace/core4d/scripts/E092/variants.tsv"
TARGET_META = REPO / "workspace/core4d/results/E094/handbox_target_projection/case_targets.json"
VARIANTS_OUT = REPO / "workspace/core4d/scripts/E094/variants.tsv"
BUILD_META_OUT = REPO / "workspace/core4d/results/E094/cem/task_build_meta.json"

FIELDS = [
    "route",
    "case_id",
    "variant",
    "source_task",
    "derived_task",
    "person_idx",
    "split",
    "object",
    "role",
    "note",
    "target_case_id",
    "target_npz",
]

CASE_TARGET = {
    "C1": "box004_083_p2",
    "C2": "box026_039_p2",
    "C3": "box026_135_p2",
}

VARIANT_NAME = {
    "C1": "E094P1_box004_083_p2_hbproj",
    "C2": "E094P2_box026_039_p2_hbproj",
    "C3": "E094P3_box026_135_p2_hbproj",
}


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(REPO))
    except ValueError:
        return str(path)


def read_e092_spider_rows(path: Path) -> list[dict[str, str]]:
    rows = []
    with path.open("r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(
            (line for line in f if line.strip() and not line.startswith("#")),
            delimiter="\t",
            fieldnames=["route", "case_id", "variant", "source_task", "derived_task", "person_idx", "split", "object", "role", "note"],
        )
        for row in reader:
            if row["route"] == "spider_dyn" and row["case_id"] in CASE_TARGET:
                rows.append(row)
    return rows


def read_target_map(path: Path) -> dict[str, str]:
    data = json.loads(path.read_text(encoding="utf-8"))
    out = {}
    for row in data:
        case_id = row["case_id"]
        target = REPO / row["target_npz"]
        if not target.is_file():
            raise FileNotFoundError(target)
        out[case_id] = rel(target)
    return out


def write_override(row: dict[str, str]) -> Path:
    path = OVERRIDE_ROOT / f"core4d_{row['variant']}.yaml"
    base = f"core4d_{row['source_variant']}"
    content = f"""# @package _global_
# Auto-generated by workspace/core4d/scripts/E094/build_cem_tasks.py.
# E094 adaptive-support handbox-aware external target projection.
defaults:
  - {base}
  - _self_

task: {row['derived_task']}

contact_hdmi_dynamic_target: true
contact_hdmi_target_source: external
contact_hdmi_target_path: {row['target_npz']}
contact_hdmi_target_time_axis: auto
contact_hdmi_target_uses_eef_offset: false
contact_hdmi_eef_offset: [0.05, 0.0, 0.0]

# Keep E092's no-mask CEM behavior: target is filled for every frame.
contact_hdmi_mask_source: ""
contact_hdmi_mask_path: ""
contact_hdmi_mask_person_idx: {row['person_idx']}
contact_hdmi_mask_time_axis: auto
"""
    path.write_text(content, encoding="utf-8")
    return path


def write_variants(rows: list[dict[str, str]]) -> None:
    VARIANTS_OUT.parent.mkdir(parents=True, exist_ok=True)
    with VARIANTS_OUT.open("w", encoding="utf-8", newline="") as f:
        f.write("# E094 variants generated by build_cem_tasks.py\n")
        f.write("# " + "\t".join(FIELDS) + "\n")
        writer = csv.DictWriter(f, fieldnames=FIELDS, delimiter="\t", lineterminator="\n")
        writer.writerows(rows)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--e092-variants", type=Path, default=E092_VARIANTS)
    parser.add_argument("--target-meta", type=Path, default=TARGET_META)
    args = parser.parse_args()

    target_map = read_target_map(args.target_meta)
    rows: list[dict[str, str]] = []
    meta: list[dict[str, Any]] = []
    for base in read_e092_spider_rows(args.e092_variants):
        target_case = CASE_TARGET[base["case_id"]]
        target_npz = target_map[target_case]
        row = {
            "route": "cem_hbproj",
            "case_id": base["case_id"],
            "variant": VARIANT_NAME[base["case_id"]],
            "source_task": base["source_task"],
            "derived_task": base["derived_task"],
            "person_idx": base["person_idx"],
            "split": base["split"],
            "object": base["object"],
            "role": base["role"],
            "note": f"E094 adaptive-support external target from {target_case}; base={base['variant']}.",
            "target_case_id": target_case,
            "target_npz": target_npz,
            "source_variant": base["variant"],
        }
        override = write_override(row)
        rows.append({k: row[k] for k in FIELDS})
        meta.append({**row, "override": rel(override)})
        print(f"[E094-build] {row['variant']} base={base['variant']} target={target_npz}")

    write_variants(rows)
    BUILD_META_OUT.parent.mkdir(parents=True, exist_ok=True)
    BUILD_META_OUT.write_text(json.dumps(meta, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {rel(VARIANTS_OUT)}")
    print(f"wrote {rel(BUILD_META_OUT)}")


if __name__ == "__main__":
    main()
