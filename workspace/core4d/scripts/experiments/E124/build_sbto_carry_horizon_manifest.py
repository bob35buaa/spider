#!/usr/bin/env python3
"""Build E124 SBTO carry-horizon diagnostic manifest."""

from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any

import mujoco


REPO = Path(__file__).resolve().parents[4]
TASK_ROOT = REPO / "example_datasets/processed/core4d/unitree_g1/humanoid_object"
OVERRIDE_ROOT = REPO / "examples/config/override"
SCRIPTS_ROOT = REPO / "workspace/core4d/scripts/E124"
RESULTS_ROOT = REPO / "workspace/core4d/results/E124"
PREFLIGHT_ROOT = RESULTS_ROOT / "preflight"
E120_VARIANTS = REPO / "workspace/core4d/scripts/E120/variants.tsv"
E121_VARIANTS = REPO / "workspace/core4d/scripts/E121/variants.tsv"
VARIANTS_TSV = SCRIPTS_ROOT / "variants.tsv"
PREFLIGHT_TSV = PREFLIGHT_ROOT / "phaseA_preflight.tsv"
SUMMARY_JSON = PREFLIGHT_ROOT / "phaseA_manifest_summary.json"
SUMMARY_MD = PREFLIGHT_ROOT / "phaseA_manifest_summary.md"

FIELDS = [
    "ordinal",
    "variant",
    "source_task",
    "derived_task",
    "person_idx",
    "split",
    "case_id",
    "e109_case_id",
    "object_key",
    "ablation",
    "mask_path",
    "source_override",
    "baseline_npz_path",
    "e113_hold_npz_path",
    "e113_hold_video_path",
    "phase_scope",
    "diagnostic_queue",
    "holdout_reason",
]

CASE_SPLITS = {
    "box021_029_p2": ("local-gpu0", "main_upright_carry"),
    "box021_035_p2": ("remote-gpu0", "companion_lowerbody_repair"),
    "box021_035_p1": ("remote-gpu1", "strict_guard"),
    "box004_083_p2": ("local-gpu0", "box004_contact_guard"),
}

VARIANT_SOURCES = [
    ("sbto_support_surface", E120_VARIANTS, "support_surface_direct"),
    ("sbto_terminal_soft", E121_VARIANTS, "terminal_soft_surface"),
]


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(REPO))
    except ValueError:
        return str(path)


def repo_path(path: str) -> Path:
    p = Path(path)
    return p if p.is_absolute() else REPO / p


def read_variants(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as f:
        lines = (line for line in f if line.strip() and not line.startswith("#"))
        return list(csv.DictReader(lines, fieldnames=FIELDS, delimiter="\t"))


def scene_loads(task: str) -> bool:
    scene = TASK_ROOT / task / "scene_act.xml"
    mujoco.MjModel.from_xml_path(str(scene))
    return True


def source_row(case_id: str, source_path: Path, ablation: str) -> dict[str, str]:
    rows = read_variants(source_path)
    for row in rows:
        if row["case_id"] == case_id and row["ablation"] == ablation:
            return row
    raise KeyError(f"{source_path} missing case={case_id} ablation={ablation}")


def build_rows() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    ordinal = 1
    for case_id, (split, phase_scope) in CASE_SPLITS.items():
        for ablation, source_path, source_ablation in VARIANT_SOURCES:
            src = source_row(case_id, source_path, source_ablation)
            base_variant = src["variant"]
            rows.append(
                {
                    **{field: src.get(field, "") for field in FIELDS},
                    "ordinal": ordinal,
                    "variant": f"E124_{case_id}_{ablation}",
                    "split": split,
                    "ablation": ablation,
                    "source_override": f"core4d_{base_variant}",
                    "phase_scope": phase_scope,
                    "_base_variant": base_variant,
                    "_source_ablation": source_ablation,
                }
            )
            ordinal += 1
    return rows


def write_tsv(path: Path, rows: list[dict[str, Any]], fields: list[str], comment: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        f.write(f"# {comment}\n")
        f.write("# " + "\t".join(fields) + "\n")
        writer = csv.DictWriter(f, fieldnames=fields, delimiter="\t", lineterminator="\n")
        for row in rows:
            writer.writerow({field: row.get(field, "") for field in fields})


def override_text(row: dict[str, Any]) -> str:
    return f"""# @package _global_
# Auto-generated by workspace/core4d/scripts/E124/build_sbto_carry_horizon_manifest.py.
# E124 SBTO carry horizon; case={row['case_id']} ablation={row['ablation']}.
defaults:
  - {row['source_override']}
  - _self_

task: {row['derived_task']}

use_sbto: true
sbto_sigma_min: 0.03
sbto_max_iter_per_knot: 12
sbto_knot_dt: 0.25
sbto_elite_fraction: 0.03
sbto_mean_momentum: 0.95
sbto_cov_momentum: 0.2

video_camera: auto
"""


def write_overrides(rows: list[dict[str, Any]]) -> list[str]:
    OVERRIDE_ROOT.mkdir(parents=True, exist_ok=True)
    paths = []
    for row in rows:
        path = OVERRIDE_ROOT / f"core4d_{row['variant']}.yaml"
        path.write_text(override_text(row), encoding="utf-8")
        paths.append(rel(path))
    return paths


def write_preflight(rows: list[dict[str, Any]]) -> dict[str, Any]:
    preflight_rows: list[dict[str, Any]] = []
    for row in rows:
        out = {
            **{field: row[field] for field in FIELDS},
            "scene_act_exists": (TASK_ROOT / row["derived_task"] / "scene_act.xml").is_file(),
            "scene_act_loads": scene_loads(row["derived_task"]),
            "trajectory_exists": (TASK_ROOT / row["derived_task"] / "0/trajectory_kinematic.npz").is_file(),
            "mask_exists": repo_path(row["mask_path"]).is_file(),
            "baseline_exists": repo_path(row["baseline_npz_path"]).is_file(),
            "e113_hold_exists": repo_path(row["e113_hold_npz_path"]).is_file(),
            "source_override_exists": (OVERRIDE_ROOT / f"{row['source_override']}.yaml").is_file(),
            "override_exists": (OVERRIDE_ROOT / f"core4d_{row['variant']}.yaml").is_file(),
            "use_sbto": True,
            "sbto_max_iter_per_knot": 12,
            "sbto_knot_dt": 0.25,
            "base_variant": row["_base_variant"],
            "source_ablation": row["_source_ablation"],
        }
        preflight_rows.append(out)
    preflight_fields = FIELDS + [
        "scene_act_exists",
        "scene_act_loads",
        "trajectory_exists",
        "mask_exists",
        "baseline_exists",
        "e113_hold_exists",
        "source_override_exists",
        "override_exists",
        "use_sbto",
        "sbto_max_iter_per_knot",
        "sbto_knot_dt",
        "base_variant",
        "source_ablation",
    ]
    write_tsv(PREFLIGHT_TSV, preflight_rows, preflight_fields, "E124 Phase A preflight")
    required = [
        "scene_act_exists",
        "scene_act_loads",
        "trajectory_exists",
        "mask_exists",
        "baseline_exists",
        "e113_hold_exists",
        "source_override_exists",
        "override_exists",
        "use_sbto",
    ]
    all_ok = all(all(row[key] is True for key in required) for row in preflight_rows)
    return {
        "variants": len(rows),
        "cases": len(CASE_SPLITS),
        "ablations": [item[0] for item in VARIANT_SOURCES],
        "all_preflight_ok": all_ok,
        "preflight_tsv": rel(PREFLIGHT_TSV),
        "variants_tsv": rel(VARIANTS_TSV),
        "override_paths": [rel(OVERRIDE_ROOT / f"core4d_{row['variant']}.yaml") for row in rows],
    }


def write_summary_md(rows: list[dict[str, Any]], summary: dict[str, Any]) -> None:
    split_counts: dict[str, int] = {}
    for row in rows:
        split_counts[row["split"]] = split_counts.get(row["split"], 0) + 1
    lines = [
        "# E124 SBTO Carry Horizon Manifest Summary",
        "",
        f"- variants: `{summary['variants']}`",
        f"- cases: `{summary['cases']}`",
        f"- ablations: `{len(summary['ablations'])}`",
        f"- all_preflight_ok: `{summary['all_preflight_ok']}`",
        "",
        "| split | variants |",
        "|---|---:|",
    ]
    for split, count in sorted(split_counts.items()):
        lines.append(f"| `{split}` | {count} |")
    lines.extend(["", "## Variants", ""])
    for row in rows:
        lines.append(
            f"- `{row['variant']}`: `{row['source_override']}` -> `{row['ablation']}` "
            f"({row['case_id']}, {row['split']})"
        )
    SUMMARY_MD.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    rows = build_rows()
    write_tsv(VARIANTS_TSV, rows, FIELDS, "E124 SBTO carry horizon variants")
    write_overrides(rows)
    summary = write_preflight(rows)
    SUMMARY_JSON.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY_JSON.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    write_summary_md(rows, summary)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
