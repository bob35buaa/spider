#!/usr/bin/env python3
"""E210 P3: write + audit the 15 Hydra override YAMLs for aug x G1only.

Each override inherits E202's aug PRG override verbatim and changes exactly one
key -- ``scene_name`` -> the gravcomp sidecar written in P2. Nothing else: same
aug reference trajectory, same 3cm mask, same E178 five-segment proxy, same E174
PRG reward/gate, same 1024x32 seed 0 budget.

The audit composes BOTH sides through Hydra and diffs every resolved key,
requiring the symmetric difference to be exactly {"scene_name"}. That is what
makes "single variable vs E202" checkable rather than asserted.

It also pins the hand gate to the E163 default (A0) -- imported from the same
module E207 uses. Getting this wrong is the one failure mode that would silently
turn E210 into an aug x G1A2 arm and make the E207 comparison meaningless.

Usage:
    .venv/bin/python workspace/core4d/scripts/experiments/E210/build_overrides.py
    ... --no-audit
    ... --limit N
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import e210_common as C  # noqa: E402

HEADER = "# @package _global_\n# Auto-generated by E210/build_overrides.py.\n"

#: Keys allowed to differ between the composed E202 and E210 configs.
ALLOWED_DIFF = {"scene_name"}


def write_override(row: dict[str, str]) -> Path:
    out = C.override_path(row["case_id"], row["aug_variant"])
    body = (
        f"{HEADER}"
        "# E210 aug x G1only = E202 bucket aug (E178 proxy + E174 PRG, omnirt_v2)\n"
        "# + object gravcomp=1, hand-gate left at the E163 default (A0).\n"
        f"# Single variable vs {row['override_id']}: scene_name -> gravcomp sidecar.\n"
        "defaults:\n"
        f"- {C.base_override_id(row)}\n"
        "- _self_\n"
        f"scene_name: {C.SCENE_NAME}\n"
    )
    out.write_text(body, encoding="utf-8")
    return out


def _compose(override_id: str) -> dict[str, Any]:
    from hydra import compose, initialize_config_dir
    from omegaconf import OmegaConf

    config_dir = str((C.REPO / "examples/config").resolve())
    with initialize_config_dir(version_base=None, config_dir=config_dir):
        cfg = compose(config_name="default", overrides=[f"+override={override_id}"])
    out = OmegaConf.to_container(cfg, resolve=True)
    assert isinstance(out, dict)
    return out


def audit_row(row: dict[str, str]) -> list[str]:
    base = _compose(C.base_override_id(row))
    cand = _compose(C.override_id(row["case_id"], row["aug_variant"]))
    fails: list[str] = []

    drift = {
        key
        for key in set(base) | set(cand)
        if base.get(key, "\0missing") != cand.get(key, "\0missing")
    }
    if unexpected := drift - ALLOWED_DIFF:
        fails.append(
            "non_axis_drift:"
            + ",".join(f"{k}({base.get(k)}->{cand.get(k)})" for k in sorted(unexpected))
        )
    if "scene_name" not in drift:
        fails.append("scene_name did not change vs E202")
    if cand.get("scene_name") != C.SCENE_NAME:
        fails.append(f"scene_name={cand.get('scene_name')}!={C.SCENE_NAME}")
    if base.get("scene_name") != C.BASE_SCENE_NAME:
        fails.append(f"E202 base scene_name={base.get('scene_name')}!={C.BASE_SCENE_NAME}")

    # A0: the hand gate must stay at the E163 default. E202 does not set these
    # keys at all, so this checks the COMPOSED effective value, not the file.
    for key, want in C.E163_HAND_GATE.items():
        got = cand.get(key)
        if got is None or abs(float(got) - want) > 1e-9:
            fails.append(f"{key}={got}!=E163_default({want})")

    # PRG + E178 union-SDF collision must survive untouched.
    if float(cand.get("leg_object_penalty_scale", 0.0)) != 2.0:
        fails.append(f"PRG leg_object_penalty_scale={cand.get('leg_object_penalty_scale')}!=2.0")
    if not bool(cand.get("cem_leg_gate_enabled", False)):
        fails.append("PRG cem_leg_gate_enabled!=true")
    if cand.get("object_collision_sdf_mode") != "union":
        fails.append(f"object_collision_sdf_mode={cand.get('object_collision_sdf_mode')}")
    if not bool(cand.get("object_collision_sdf_batch_groups", False)):
        fails.append("object_collision_sdf_batch_groups!=true")

    # The aug task must be the augmented one, not the orig it was seeded from.
    if cand.get("task") != row["target_task"]:
        fails.append(f"task={cand.get('task')}!={row['target_task']}")
    return fails


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--audit", action="store_true", default=True)
    ap.add_argument("--no-audit", dest="audit", action="store_false")
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()

    rows = C.load_variants()
    if args.limit:
        rows = rows[: args.limit]
    for row in rows:
        write_override(row)
    print(f"wrote {len(rows)} override YAMLs to {C.OVERRIDE_DIR.relative_to(C.REPO)}")

    if not args.audit:
        return 0
    failures: dict[str, list[str]] = {}
    for row in rows:
        if fails := audit_row(row):
            failures[C.override_id(row["case_id"], row["aug_variant"])] = fails
    if failures:
        for override, fails in failures.items():
            print(f"  FAIL {override}: {'; '.join(fails)}")
        raise SystemExit(f"override audit FAILED for {len(failures)} configs")
    print(
        f"audit PASS: {len(rows)} overrides differ from their E202 parent by exactly "
        f"{sorted(ALLOWED_DIFF)}; hand-gate == E163 default (A0); PRG + union SDF on"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
