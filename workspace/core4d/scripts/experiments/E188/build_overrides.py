#!/usr/bin/env python3
"""Generate 15 E188 overrides whose only explicit delta is scene_name."""

from __future__ import annotations

import argparse
import json
import os
import tempfile
from pathlib import Path
from typing import Any

import yaml
from hydra import compose, initialize_config_dir
from omegaconf import OmegaConf

from common import REPO, S0, read_tsv, relative, sha256, write_json

AUTHORITY = S0 / "authority_manifest.tsv"
OUTPUT = S0 / "overrides_manifest.json"
OVERRIDE_DIR = REPO / "examples/config/override"
SCENE_NAME = "scene_act_E188_mass5kg"


def override_id(case_id: str) -> str:
    return f"core4d_E188_{case_id}_mass5kg"


def payload(row: dict[str, str]) -> dict[str, Any]:
    return {"defaults": [row["e187_override_id"], "_self_"], "scene_name": SCENE_NAME}


def text(row: dict[str, str]) -> str:
    return (
        "# @package _global_\n"
        "# Auto-generated by E188 build_overrides.py; only scene_name changes.\n"
        + yaml.safe_dump(payload(row), sort_keys=False)
    )


def effective(identity: str) -> dict[str, Any]:
    with initialize_config_dir(
        version_base=None, config_dir=str((REPO / "examples/config").resolve())
    ):
        value = OmegaConf.to_container(
            compose(config_name="default", overrides=[f"+override={identity}"]), resolve=True
        )
    if not isinstance(value, dict):
        raise RuntimeError("Hydra effective config is not a dictionary")
    return value


def write_immutable(path: Path, data: bytes) -> None:
    if path.is_file():
        if path.read_bytes() != data:
            raise RuntimeError(f"refusing to replace E188 override: {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, raw = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
        os.replace(raw, path)
    except BaseException:
        Path(raw).unlink(missing_ok=True)
        raise


def build(*, freeze: bool) -> dict[str, Any]:
    rows = read_tsv(AUTHORITY)
    if len(rows) != 15:
        raise RuntimeError("E188 authority must contain 15 rows")
    output = []
    for row in rows:
        identity = override_id(row["case_id"])
        path = OVERRIDE_DIR / f"{identity}.yaml"
        data = text(row).encode()
        if freeze:
            write_immutable(path, data)
        else:
            write_immutable(path, data)
        baseline = effective(row["e187_override_id"])
        candidate = effective(identity)
        changed = {
            key: {"e187": baseline.get(key), "e188": candidate.get(key)}
            for key in sorted(set(baseline) | set(candidate))
            if baseline.get(key) != candidate.get(key)
        }
        unexpected = sorted(set(changed) - {"scene_name", "model_path"})
        if unexpected or candidate.get("scene_name") != SCENE_NAME:
            raise RuntimeError(f"{row['case_id']}: unexpected config drift {unexpected}")
        output.append(
            {
                "ordinal": int(row["ordinal"]),
                "case_id": row["case_id"],
                "object_key": row["object_key"],
                "source_override_id": row["e187_override_id"],
                "source_override_path": row["e187_override_path"],
                "source_override_sha256": row["e187_override_sha256"],
                "override_id": identity,
                "override_path": relative(path),
                "override_sha256": sha256(path),
                "scene_name": SCENE_NAME,
                "scene_sha256": row["scene_sha256"],
                "grid_manifest": row["grid_manifest"],
                "grid_manifest_sha256": row["grid_manifest_sha256"],
                "epsilon_grid_m": float(row["epsilon_grid_m"]),
                "explicit_changed_fields": ["scene_name"],
                "effective_changed_fields": changed,
                "status": "PASS",
            }
        )
    result = {
        "schema": "e188_mass5kg_overrides_v1",
        "experiment_id": "E188",
        "status": "PASS",
        "row_count": len(output),
        "explicit_allowed_diff": ["scene_name"],
        "rows": output,
    }
    if freeze:
        write_json(OUTPUT, result, immutable=True)
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=("preflight", "freeze"))
    args = parser.parse_args()
    result = build(freeze=args.mode == "freeze")
    print(json.dumps({"status": result["status"], "rows": result["row_count"], "output": relative(OUTPUT), "written": args.mode == "freeze"}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
