#!/usr/bin/env python3
"""E199: build CEM overrides + the local 8-GPU priority manifest from the
augmented-task artifacts.

Input authority is e199_aug_artifacts.tsv (produced by build_augmented_tasks.py).
For each of the 6 variants per case this:
  1. writes the base task Hydra yaml `core4d_{aug_task}.yaml` -- a copy of the
     historical base task yaml with `task:` swapped to the aug task and
     `contact_hdmi_mask_path:` pointed at the reused (original) 3cm mask;
  2. writes the E199 PRG override `core4d_E199_{case}__aug_{variant}_PRG.yaml`
     (defaults -> aug base task yaml; identical leg-gate/penalty payload to E173);
  3. emits a priority manifest row (P0 orig -> P1 trans -> P2 rot) with frozen
     full CEM budget (seed 0, 1024 samples, 32 opt steps) and SHA provenance.

Never overwrites the historical base task yaml or scenes.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import e199_common as C  # noqa: E402

ARTIFACTS = C.RESULTS / "data_preprocess/manifests/e199_aug_artifacts.tsv"
CEM_ROOT = "workspace/core4d/results/E199/s6_downstream/cem/full"
RENDER_ROOT = "workspace/core4d/results/E199/s6_downstream/render/full"


def base_task_override_id(aug_task: str) -> str:
    return C.safe_id(f"core4d_{aug_task}")


def write_base_task_yaml(base_task: str, aug_task: str, mask_rel: str) -> Path:
    """Copy the historical base task yaml, swap task + mask path -> aug base yaml."""
    src = C.OVERRIDE_DIR / f"core4d_{base_task}.yaml"
    if not src.is_file():
        raise FileNotFoundError(f"historical base task yaml missing: {src}")
    out = C.OVERRIDE_DIR / f"{base_task_override_id(aug_task)}.yaml"
    lines = src.read_text(encoding="utf-8").splitlines()
    swapped: list[str] = []
    for line in lines:
        if line.startswith("task:"):
            swapped.append(f"task: {aug_task}")
        elif line.startswith("contact_hdmi_mask_path:"):
            swapped.append(f'contact_hdmi_mask_path: "{mask_rel}"')
        else:
            swapped.append(line)
    header = ("# @package _global_\n"
              f"# E199 augmented base task yaml (copied from core4d_{base_task}.yaml).\n"
              f"# aug_task: {aug_task}\n")
    out.write_text(header + "\n".join(swapped) + "\n", encoding="utf-8")
    return out


def write_prg_override(case_id: str, aug_variant: str, base_override_id: str) -> Path:
    override_id = C.safe_id(f"core4d_E199_{case_id}_aug_{aug_variant}_PRG")
    out = C.OVERRIDE_DIR / f"{override_id}.yaml"
    header = "# @package _global_\n# Auto-generated by E199 build_aug_manifest.py.\n"
    out.write_text(header + yaml.safe_dump(C.prg_override_payload(base_override_id), sort_keys=False),
                   encoding="utf-8")
    return out


def artifact_paths(variant_id: str) -> dict[str, str]:
    return {
        "variant": variant_id,
        "result_npz": f"{CEM_ROOT}/{variant_id}.npz",
        "outdir_npz": f"{CEM_ROOT}/{variant_id}_outdir_full/trajectory_mjwp_act.npz",
        "config_act": f"{CEM_ROOT}/{variant_id}_outdir_full/config_act.yaml",
        "video": f"{RENDER_ROOT}/{variant_id}_full.mp4",
        "log": f"logs/E199/cem/full/{variant_id}.log",
    }


def build(artifacts: Path) -> tuple[list[dict[str, Any]], list[str]]:
    rows_in = C.read_tsv(artifacts)
    if not rows_in:
        raise SystemExit(f"no artifact rows in {C.rel(artifacts)} -- run build_augmented_tasks.py first")
    rows: list[dict[str, Any]] = []
    blockers: list[str] = []
    for art in rows_in:
        base_task = art["base_target_task"]
        aug_task = art["target_task"]
        aug_variant = art["aug_variant"]
        case_id = art["case_id"]
        object_key = art["object_key"]
        mask_rel = art["contact_mask"]

        base_yaml = write_base_task_yaml(base_task, aug_task, mask_rel)
        base_id = base_yaml.stem
        override = write_prg_override(case_id, aug_variant, base_id)
        variant_id = C.safe_id(f"E199_{case_id}_aug_{aug_variant}_PRG")
        tier = C.TIER_OF_VARIANT[aug_variant]

        row = {
            "tier": tier, "experiment": "E199", "arm": "A0PRG",
            "object_key": object_key, "case_id": case_id, "aug_variant": aug_variant,
            "aug_translation": art.get("aug_translation", ""),
            "aug_rotation_rad": art.get("aug_rotation_rad", ""),
            "base_target_task": base_task, "target_task": aug_task,
            "target_scene": C.rel(C.TASK_ROOT / aug_task / "scene.xml"),
            "trajectory": art["trajectory"], "trajectory_sha256": art["trajectory_sha256"],
            "contact_mask": mask_rel, "contact_mask_sha256": art["contact_mask_sha256"],
            "override_id": override.stem, "override_path": C.rel(override),
            "override_sha256": C.sha256(override),
            "base_scene_act": art["base_scene_act"], "base_scene_sha256": art["base_scene_sha256"],
            "scene_act": art["scene_act"], "scene_name": C.SCENE_NAME,
            "effective_scene_sha256": art["effective_scene_sha256"],
            "extra_overrides": "",
            "cem_samples": C.CEM_FULL_SAMPLES, "cem_opt_steps": C.CEM_FULL_OPT_STEPS, "cem_seed": C.CEM_SEED,
            "execution_mode": "production", "status": "", "failure_mode": "", "gpu_id": "",
            "updated_at": C.now(),
            **artifact_paths(variant_id),
        }
        # preflight: the run inputs must exist
        for label, key in (("scene", "scene_act"), ("trajectory", "trajectory"),
                           ("override", "override_path"), ("contact", "contact_mask"),
                           ("target_scene", "target_scene")):
            if not C.repo_path(row[key]).is_file():
                blockers.append(f"{variant_id}:missing:{label}")
        rows.append(row)

    rows.sort(key=lambda r: (C.TIER_RANK[r["tier"]], r["object_key"], r["aug_variant"]))
    for ordinal, row in enumerate(rows, 1):
        row["ordinal"] = ordinal
    return rows, blockers


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--scope", default="pilot", choices=["pilot", "box_fullscale"])
    parser.add_argument("--print-only", action="store_true")
    args = parser.parse_args()

    fullscale = args.scope == "box_fullscale"
    artifacts = C.FULLSCALE_ARTIFACTS if fullscale else ARTIFACTS
    manifest = C.FULLSCALE_MANIFEST if fullscale else C.FULL_MANIFEST
    authority = C.FULLSCALE_AUTHORITY if fullscale else C.AUTHORITY_TSV

    rows, blockers = build(C.repo_path(artifacts))
    C.write_tsv(manifest, rows, C.FIELDS)
    C.write_tsv(authority, rows, C.FIELDS)
    summary = {
        "created_at": C.now(), "rows": len(rows),
        "by_tier": {t: sum(r["tier"] == t for r in rows) for t in ("P0", "P1", "P2")},
        "by_object": {k: sum(r["object_key"] == k for r in rows) for k in sorted({r["object_key"] for r in rows})},
        "by_case": len({r["case_id"] for r in rows}),
        "scope": args.scope, "blockers": blockers, "full_manifest": C.rel(manifest),
        "frozen_cem": {"seed": C.CEM_SEED, "samples": C.CEM_FULL_SAMPLES, "opt_steps": C.CEM_FULL_OPT_STEPS},
    }
    summary_name = "e199_fullscale_manifest_summary.json" if fullscale else "e199_manifest_summary.json"
    C.write_json(C.MANIFEST_DIR / summary_name, summary)
    import json
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 1 if blockers else 0


if __name__ == "__main__":
    raise SystemExit(main())
