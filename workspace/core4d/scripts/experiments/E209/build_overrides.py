#!/usr/bin/env python3
"""Write + audit the 22 Hydra override YAMLs for E209 (PRG + G1 gravcomp).

Each override inherits E206's PRG config verbatim and changes exactly one key --
``scene_name`` -> the gravcomp sidecar. The A2 hand-gate that E205 applies is
deliberately NOT applied, so the hand-gate stays at its E163 default (A0).

The audit composes both the E206-PRG baseline and the E209 candidate through
Hydra and diffs every resolved key, requiring the symmetric difference to be
exactly {"scene_name"}. That is what makes "single variable vs E206 PRG"
checkable rather than asserted.

Note this allow-list is 1 key, not E206's ``ARM_DIFF_KEYS`` (12). Those 12 are
the noPRG<->PRG contrast set; E209<->E206-PRG is PRG<->PRG, so the whole leg
triple is identical on both sides and any leg-key drift would be a real defect.

Usage:
    .venv/bin/python workspace/core4d/scripts/experiments/E209/build_overrides.py
    ... --no-audit
    ... --limit N
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[5]
sys.path.insert(0, str(REPO / "workspace/core4d/scripts/experiments/E209"))

import e209_common as C  # noqa: E402

HEADER = "# @package _global_\n# Auto-generated by E209/build_overrides.py.\n"

#: Keys allowed to differ between the composed E206-PRG and E209 configs.
ALLOWED_DIFF = {"scene_name"}


def write_override(case_id: str) -> None:
    body = (
        f"{HEADER}"
        "# E209 G1 (E206 PRG + object gravcomp, A0 hand-gate) arm.\n"
        "# Single variable vs E206 PRG: scene_name -> gravcomp sidecar. No A2 retune.\n"
        "defaults:\n"
        f"- {C.base_override_id(case_id)}\n"
        "- _self_\n"
        f"scene_name: {C.SCENE}\n"
    )
    C.override_path(case_id).write_text(body, encoding="utf-8")


def _compose(override_id: str) -> dict[str, Any]:
    from hydra import compose, initialize_config_dir
    from omegaconf import OmegaConf

    config_dir = str((C.REPO / "examples/config").resolve())
    with initialize_config_dir(version_base=None, config_dir=config_dir):
        cfg = compose(config_name="default", overrides=[f"+override={override_id}"])
    out = OmegaConf.to_container(cfg, resolve=True)
    assert isinstance(out, dict)
    return out


def audit_case(case_id: str) -> list[str]:
    base = _compose(C.base_override_id(case_id))
    cand = _compose(C.override_id(case_id))
    fails: list[str] = []

    drift = {
        key
        for key in set(base) | set(cand)
        if base.get(key, "\0missing") != cand.get(key, "\0missing")
    }
    unexpected = drift - ALLOWED_DIFF
    if unexpected:
        fails.append(
            "non_axis_drift:"
            + ",".join(f"{k}({base.get(k)}->{cand.get(k)})" for k in sorted(unexpected))
        )
    if "scene_name" not in drift:
        fails.append("scene_name did not change vs E206 PRG")
    if cand.get("scene_name") != C.SCENE:
        fails.append(f"scene_name={cand.get('scene_name')}!={C.SCENE}")

    # A0: the hand gate must remain at the E163 default. This is what separates
    # E209 from a G1A2 arm -- getting it wrong silently changes two axes.
    for key, want in C.E163_HAND_GATE.items():
        got = cand.get(key)
        if got is None or abs(float(got) - float(want)) > 1e-9:
            fails.append(f"{key}={got}!=E163_default({want})")

    # PRG must still be on (E209 is E206 PRG + gravcomp, not noPRG).
    if float(cand.get("leg_object_penalty_scale", 0.0)) != 2.0:
        fails.append(f"PRG leg_object_penalty_scale={cand.get('leg_object_penalty_scale')}!=2.0")
    if not bool(cand.get("cem_leg_gate_enabled", False)):
        fails.append("PRG cem_leg_gate_enabled!=true")
    if len(cand.get("leg_object_penalty_geom_names") or []) != 16:
        fails.append(
            f"leg_object_penalty_geom_names n={len(cand.get('leg_object_penalty_geom_names') or [])}!=16"
        )
    # Not inherited -- spider/config.py fail-closes if this is lost.
    if cand.get("object_collision_sdf_mode") != "union":
        fails.append(f"object_collision_sdf_mode={cand.get('object_collision_sdf_mode')}")

    # Both arms must read the SAME contact mask: eval resolves the mask from each
    # run's own config_act.yaml, so a divergence here would make every
    # contact-derived gate incomparable between the two arms.
    if base.get("contact_hdmi_mask_path") != cand.get("contact_hdmi_mask_path"):
        fails.append(
            f"contact_hdmi_mask_path drift: {base.get('contact_hdmi_mask_path')} "
            f"-> {cand.get('contact_hdmi_mask_path')}"
        )
    return fails


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--audit", action="store_true", default=True)
    ap.add_argument("--no-audit", dest="audit", action="store_false")
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()

    cases = list(C.CASES)[: args.limit] if args.limit else list(C.CASES)
    for case_id in cases:
        write_override(case_id)
    print(f"wrote {len(cases)} override YAMLs to {C.OVERRIDE_DIR.relative_to(C.REPO)}")

    if not args.audit:
        return 0
    failures = {}
    for case_id in cases:
        fails = audit_case(case_id)
        if fails:
            failures[C.override_id(case_id)] = fails
        else:
            print(f"  {case_id:36s} PASS  diff_keys == {sorted(ALLOWED_DIFF)}")
    if failures:
        for override, fails in failures.items():
            print(f"  FAIL {override}: {'; '.join(fails)}")
        raise SystemExit(f"override audit FAILED for {len(failures)} configs")
    print(
        f"\nP2 PASS: {len(cases)} overrides differ from E206 PRG by exactly "
        f"{sorted(ALLOWED_DIFF)}; hand-gate == E163 default (A0); PRG on; mask shared"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
