#!/usr/bin/env python3
"""E206 P7: write + audit the per-case noPRG / PRG Hydra overrides.

Both arms inherit the same S5-generated dcv3 base override, so the only thing
that can differ is what each arm file itself declares. The audit composes both
arms through Hydra (no GPU, no scene files) and asserts:

  * the composed configs differ on EXACTLY ``C.ARM_DIFF_KEYS`` and nothing else
    -- plan236 C4, zero tolerance. A stray key here is a confound that would
    silently invalidate the whole arm comparison;
  * both arms keep the E163 hand gate verbatim (E206 has no A2);
  * both arms declare ``object_collision_sdf_mode: union`` -- it is NOT
    inherited, and losing it would fail-close at scene load (spider/config.py:69-79);
  * noPRG has the leg triple off, PRG has it on.

The S5 exporter writes base overrides under results/; Hydra only resolves names
in examples/config/override/, so they are installed there first.

Usage:
    .venv/bin/python .../build_overrides.py            # install bases + write + audit
    ... --limit N --no-audit
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

import e206_common as C  # noqa: E402

CEM_OVERRIDE_DIR = C.S5_DIR / "cem_overrides/overrides"
HEADER = "# @package _global_\n# Auto-generated by E206/build_overrides.py.\n"


def base_override_id(case_id: str) -> str:
    return f"core4d_dcv3_omnirt_v1_ref_fk_{case_id}"


def install_base(case_id: str) -> Path:
    """Copy the S5 base override into examples/config/override/ for Hydra."""
    src = CEM_OVERRIDE_DIR / f"{base_override_id(case_id)}.yaml"
    if not src.is_file():
        raise FileNotFoundError(f"S5 base override missing: {src}")
    dst = C.OVERRIDE_DIR / src.name
    if not dst.is_file() or dst.read_bytes() != src.read_bytes():
        shutil.copy2(src, dst)
    return dst


def _yaml_scalar(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(str(v) for v in value) + "]"
    return str(value)


def write_arm(case_id: str, arm: str) -> Path:
    lines = [
        HEADER,
        f"# E206 {arm} arm on the hand-placed lowgeom proxy (base reward "
        f"{C.BASE_REWARD_METHOD}).\n",
        "defaults:\n",
        f"- {base_override_id(case_id)}\n",
        "- _self_\n",
    ]
    for key, value in C.OVERRIDES_BY_ARM[arm].items():
        lines.append(f"{key}: {_yaml_scalar(value)}\n")
    path = C.OVERRIDE_DIR / f"{C.override_name(case_id, arm)}.yaml"
    path.write_text("".join(lines), encoding="utf-8")
    return path


def compose(override_id: str) -> dict:
    from hydra import compose as hydra_compose, initialize_config_dir
    from omegaconf import OmegaConf

    config_dir = str((C.REPO / "examples/config").resolve())
    with initialize_config_dir(version_base=None, config_dir=config_dir):
        cfg = hydra_compose(config_name="default", overrides=[f"+override={override_id}"])
    out = OmegaConf.to_container(cfg, resolve=True)
    assert isinstance(out, dict)
    return out


def audit(case_id: str) -> list[str]:
    fails: list[str] = []
    cfgs = {arm: compose(C.override_name(case_id, arm)) for arm in C.ARMS}

    # C4: the composed configs may differ on the five arm keys and nothing else.
    keys = set(cfgs["noprg"]) | set(cfgs["prg"])
    actual_diff = {
        k for k in keys
        if cfgs["noprg"].get(k, "__missing__") != cfgs["prg"].get(k, "__missing__")
    }
    unexpected = actual_diff - C.ARM_DIFF_KEYS
    if unexpected:
        fails.append(f"unexpected cross-arm diff keys: {sorted(unexpected)}")
    # scene_name must actually differ, else the two arms would run one scene.
    if "scene_name" not in actual_diff:
        fails.append("scene_name identical across arms")

    for arm, cfg in cfgs.items():
        if cfg.get("scene_name") != C.SCENE_BY_ARM[arm]:
            fails.append(f"{arm}: scene_name={cfg.get('scene_name')}")
        if cfg.get("object_collision_sdf_mode") != "union":
            fails.append(f"{arm}: object_collision_sdf_mode={cfg.get('object_collision_sdf_mode')}")
        # No A2 in E206: both arms keep the E163 hand gate exactly.
        for k, v in C.E163_HAND_GATE.items():
            got = cfg.get(k)
            if isinstance(v, bool):
                if bool(got) != v:
                    fails.append(f"{arm}: {k}={got}!=E163({v})")
            elif got is None or abs(float(got) - float(v)) > 1e-9:
                fails.append(f"{arm}: {k}={got}!=E163({v})")

    if float(cfgs["noprg"].get("leg_object_penalty_scale", -1)) != 0.0:
        fails.append(f"noprg leg_object_penalty_scale={cfgs['noprg'].get('leg_object_penalty_scale')}!=0")
    if bool(cfgs["noprg"].get("cem_leg_gate_enabled", True)):
        fails.append("noprg cem_leg_gate_enabled!=false")
    if float(cfgs["prg"].get("leg_object_penalty_scale", -1)) != 2.0:
        fails.append(f"prg leg_object_penalty_scale={cfgs['prg'].get('leg_object_penalty_scale')}!=2.0")
    if not bool(cfgs["prg"].get("cem_leg_gate_enabled", False)):
        fails.append("prg cem_leg_gate_enabled!=true")
    return fails


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cases", default="")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--no-audit", action="store_true")
    ap.add_argument("--out-dir", type=Path, default=C.S5_DIR / "arm_overrides")
    args = ap.parse_args()

    manifest = C.S3_DIR / "omnirt_v1/ref_fk/stage2b_manifest_omnirt_v1_ref_fk.tsv"
    case_ids = [r["case_id"] for r in C.read_tsv(manifest)
                if r.get("stage2b_status") == "pass"]
    if args.cases:
        want = {c.strip() for c in args.cases.split(",") if c.strip()}
        case_ids = [c for c in case_ids if c in want]
    if args.limit:
        case_ids = case_ids[: args.limit]
    if not case_ids:
        raise SystemExit("no Stage2b-passing cases")

    rows, failures = [], []
    for i, case_id in enumerate(case_ids, 1):
        row: dict[str, Any] = {"case_id": case_id}
        try:
            install_base(case_id)
            for arm in C.ARMS:
                row[f"{arm}_override"] = str(write_arm(case_id, arm).relative_to(C.REPO))
            row["audit_fails"] = "" if args.no_audit else ";".join(audit(case_id))
            row["status"] = "pass" if not row["audit_fails"] else "audit_fail"
        except Exception as exc:  # noqa: BLE001
            row["status"] = f"fail_{type(exc).__name__}"
            row["audit_fails"] = str(exc)
        if row["status"] != "pass":
            failures.append(row)
        rows.append(row)
        print(f"[{i:02d}/{len(case_ids)}] {case_id}: {row['status']} {row.get('audit_fails','')}",
              flush=True)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    C.write_tsv(args.out_dir / "arm_override_build.tsv", rows)
    (args.out_dir / "arm_override_build.json").write_text(json.dumps({
        "generated_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "n_cases": len(rows),
        "passed": sum(1 for r in rows if r["status"] == "pass"),
        "arm_diff_keys": sorted(C.ARM_DIFF_KEYS),
        "failures": failures,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"\npass={sum(1 for r in rows if r['status'] == 'pass')}/{len(rows)} "
          f"failures={len(failures)}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
