#!/usr/bin/env python3
"""Write + audit the 12 Hydra override YAMLs for E212 Stage A.

Each override inherits E206's PRG config verbatim and changes exactly one key --
``scene_name`` -> the partial-gravcomp sidecar for that arm.  The A2 hand-gate is
deliberately NOT applied, so the hand-gate stays at its E163 default (A0), the
same as E206 PRG and E209 G1.  That is what keeps all five points of the g-curve
on one ruler.

The audit composes both the E206-PRG baseline and the E212 candidate through
Hydra and diffs every resolved key, requiring the symmetric difference to be
exactly {"scene_name"}.  It additionally cross-checks the three arms against
each other: they must differ from one another by that same one key, otherwise
two "different" g values would be running the same scene.

Usage:
    .venv/bin/python workspace/core4d/scripts/experiments/E212/build_overrides.py
    ... --no-audit
    ... --limit N
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[5]
sys.path.insert(0, str(REPO / "workspace/core4d/scripts/experiments/E212"))

import e212_common as C  # noqa: E402

HEADER = "# @package _global_\n# Auto-generated by E212/build_overrides.py.\n"

#: Keys allowed to differ between the composed E206-PRG and E212 configs.
#: Stage A is scene-only.  Stage B (hand_support) would have to widen this
#: explicitly -- including the derived `hand_support_geom_ids`, which
#: spider/config.py:1352-1362 fills in from the names.
ALLOWED_DIFF = {"scene_name"}


def write_override(case_id: str, arm: str) -> None:
    body = (
        f"{HEADER}"
        f"# E212 Stage A arm {arm}: E206 PRG + object gravcomp={C.gravcomp_str(arm)}.\n"
        "# Single variable vs E206 PRG: scene_name -> partial-gravcomp sidecar.\n"
        "# A0 hand-gate (E163 default), no A2 retune -- same ruler as E209 G1.\n"
        "defaults:\n"
        f"- {C.base_override_id(case_id)}\n"
        "- _self_\n"
        f"scene_name: {C.SCENE_BY_ARM[arm]}\n"
    )
    C.override_path(case_id, arm).write_text(body, encoding="utf-8")


def _compose(override_id: str) -> dict[str, Any]:
    from hydra import compose, initialize_config_dir
    from omegaconf import OmegaConf

    config_dir = str((C.REPO / "examples/config").resolve())
    with initialize_config_dir(version_base=None, config_dir=config_dir):
        cfg = compose(config_name="default", overrides=[f"+override={override_id}"])
    out = OmegaConf.to_container(cfg, resolve=True)
    assert isinstance(out, dict)
    return out


def _drift(a: dict[str, Any], b: dict[str, Any]) -> set[str]:
    return {
        key
        for key in set(a) | set(b)
        if a.get(key, "\0missing") != b.get(key, "\0missing")
    }


def audit_case(case_id: str) -> list[str]:
    base = _compose(C.base_override_id(case_id))
    fails: list[str] = []
    composed: dict[str, dict[str, Any]] = {}

    for arm in C.ARM_ORDER:
        cand = _compose(C.override_id(case_id, arm))
        composed[arm] = cand

        unexpected = _drift(base, cand) - ALLOWED_DIFF
        if unexpected:
            fails.append(
                f"{arm} non_axis_drift:"
                + ",".join(f"{k}({base.get(k)}->{cand.get(k)})" for k in sorted(unexpected))
            )
        if "scene_name" not in _drift(base, cand):
            fails.append(f"{arm} scene_name did not change vs E206 PRG")
        if cand.get("scene_name") != C.SCENE_BY_ARM[arm]:
            fails.append(f"{arm} scene_name={cand.get('scene_name')}!={C.SCENE_BY_ARM[arm]}")

        # A0: the hand gate must remain at the E163 default. Getting this wrong
        # silently changes two axes and makes the g-curve incomparable to E209.
        for key, want in C.E163_HAND_GATE.items():
            got = cand.get(key)
            if got is None or abs(float(got) - float(want)) > 1e-9:
                fails.append(f"{arm} {key}={got}!=E163_default({want})")

        # PRG must still be on (E212 is E206 PRG + partial gravcomp, not noPRG).
        if float(cand.get("leg_object_penalty_scale", 0.0)) != 2.0:
            fails.append(f"{arm} PRG leg_object_penalty_scale={cand.get('leg_object_penalty_scale')}!=2.0")
        if not bool(cand.get("cem_leg_gate_enabled", False)):
            fails.append(f"{arm} PRG cem_leg_gate_enabled!=true")
        if len(cand.get("leg_object_penalty_geom_names") or []) != 16:
            fails.append(
                f"{arm} leg_object_penalty_geom_names "
                f"n={len(cand.get('leg_object_penalty_geom_names') or [])}!=16"
            )
        # Not inherited -- spider/config.py fail-closes if this is lost.
        if cand.get("object_collision_sdf_mode") != "union":
            fails.append(f"{arm} object_collision_sdf_mode={cand.get('object_collision_sdf_mode')}")

        # Every arm must read the SAME contact mask as the baseline: eval
        # resolves the mask from each run's own config_act.yaml, so a divergence
        # would make every contact-derived gate incomparable across the sweep.
        if base.get("contact_hdmi_mask_path") != cand.get("contact_hdmi_mask_path"):
            fails.append(
                f"{arm} contact_hdmi_mask_path drift: {base.get('contact_hdmi_mask_path')} "
                f"-> {cand.get('contact_hdmi_mask_path')}"
            )

    # Arms must differ from EACH OTHER by scene_name only -- otherwise two g
    # values would resolve to the same scene and the sweep would silently have
    # fewer points than it reports.
    arms = list(C.ARM_ORDER)
    for i, left in enumerate(arms):
        for right in arms[i + 1:]:
            drift = _drift(composed[left], composed[right])
            if drift != {"scene_name"}:
                fails.append(f"{left}vs{right} drift={sorted(drift)}!=['scene_name']")
    return fails


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--audit", action="store_true", default=True)
    ap.add_argument("--no-audit", dest="audit", action="store_false")
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()

    cases = list(C.CASES)[: args.limit] if args.limit else list(C.CASES)
    for case_id in cases:
        for arm in C.ARM_ORDER:
            write_override(case_id, arm)
    print(
        f"wrote {len(cases) * len(C.ARMS)} override YAMLs to "
        f"{C.OVERRIDE_DIR.relative_to(C.REPO)}"
    )

    if not args.audit:
        return 0
    failures = {}
    for case_id in cases:
        fails = audit_case(case_id)
        if fails:
            failures[case_id] = fails
        else:
            print(f"  {case_id:32s} PASS  {len(C.ARMS)} arms, diff_keys == {sorted(ALLOWED_DIFF)}")
    if failures:
        for case_id, fails in failures.items():
            print(f"  FAIL {case_id}: {'; '.join(fails)}")
        raise SystemExit(f"override audit FAILED for {len(failures)} cases")
    print(
        f"\nP3 PASS: {len(cases) * len(C.ARMS)} overrides differ from E206 PRG by exactly "
        f"{sorted(ALLOWED_DIFF)}; arms mutually scene-only; hand-gate == E163 (A0); PRG on; mask shared"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
