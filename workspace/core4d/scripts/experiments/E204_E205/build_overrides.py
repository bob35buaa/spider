#!/usr/bin/env python3
"""Write + audit the 27x2 Hydra override YAMLs for E204 (noPRG) and E205 (G1A2).

E204 override inherits the E167A base task directly (bypassing E174 PRG), so the
leg penalty/gate fall back to defaults (0 / false); it re-declares the E178 object
SDF union + points scene_name at the noPRG scene. E205 override inherits the E178
config verbatim (PRG on + object SDF union) and only points scene_name at the G1
gravcomp sidecar + applies the A2 hand-gate three-field retune.

The audit composes each override via Hydra (no GPU / scene files needed) and asserts
the single-variable arm contract:

  * E204: leg_object_penalty_scale==0, cem_leg_gate_enabled==False,
          object_collision_sdf_mode=="union", hand-gate == E163 default (untouched).
  * E205: cem_hand_gate_* == A2_GATE, leg penalty 2.0 + leg gate True (PRG kept),
          object_collision_sdf_mode=="union".

Usage:
    .venv/bin/python workspace/core4d/scripts/experiments/E204_E205/build_overrides.py
    ... --audit          # also compose-audit every written override (default on)
    ... --limit N
"""

from __future__ import annotations

import argparse

import e204e205_common as C

HEADER = "# @package _global_\n# Auto-generated by E204_E205/build_overrides.py.\n"


def write_e204(case_id: str) -> None:
    body = (
        f"{HEADER}"
        f"# E204 noPRG (E167A) arm on E178 contactAlignedTop object proxy.\n"
        "defaults:\n"
        f"- {C.dcv3_override_id(case_id)}\n"
        "- _self_\n"
        f"scene_name: {C.E204_SCENE}\n"
        "object_collision_sdf_mode: union\n"
        "object_collision_sdf_batch_groups: true\n"
    )
    C.override_path("noprg_e204", case_id).write_text(body, encoding="utf-8")


def write_e205(case_id: str) -> None:
    a2 = C.A2_GATE
    body = (
        f"{HEADER}"
        f"# E205 G1A2 (PRG + G1 gravcomp + A2 hand-gate) arm on E178 contactAlignedTop.\n"
        "defaults:\n"
        f"- {C.e178_override_id(case_id)}\n"
        "- _self_\n"
        f"scene_name: {C.E205_SCENE}\n"
        f"cem_hand_gate_min_sdf_m: {a2['cem_hand_gate_min_sdf_m']}\n"
        f"cem_hand_gate_max_violation_pct: {a2['cem_hand_gate_max_violation_pct']}\n"
        f"cem_hand_gate_hard_floor_m: {a2['cem_hand_gate_hard_floor_m']}\n"
    )
    C.override_path("g1a2_e205", case_id).write_text(body, encoding="utf-8")


def _compose(override_id: str) -> dict:
    from hydra import compose, initialize_config_dir
    from omegaconf import OmegaConf
    config_dir = str((C.REPO / "examples/config").resolve())
    with initialize_config_dir(version_base=None, config_dir=config_dir):
        cfg = compose(config_name="default", overrides=[f"+override={override_id}"])
    out = OmegaConf.to_container(cfg, resolve=True)
    assert isinstance(out, dict)
    return out


def audit_e204(case_id: str) -> list[str]:
    cfg = _compose(C.override_id("noprg_e204", case_id))
    fails = []
    if float(cfg.get("leg_object_penalty_scale", 0.0)) != 0.0:
        fails.append(f"leg_object_penalty_scale={cfg.get('leg_object_penalty_scale')}!=0")
    if bool(cfg.get("cem_leg_gate_enabled", False)):
        fails.append("cem_leg_gate_enabled!=false")
    if cfg.get("object_collision_sdf_mode") != "union":
        fails.append(f"object_collision_sdf_mode={cfg.get('object_collision_sdf_mode')}")
    if cfg.get("scene_name") != C.E204_SCENE:
        fails.append(f"scene_name={cfg.get('scene_name')}")
    for k, v in C.E163_HAND_GATE.items():  # A2 must NOT be applied to noPRG
        if abs(float(cfg.get(k, float("nan"))) - v) > 1e-9:
            fails.append(f"{k}={cfg.get(k)}!=E163_default({v})")
    return fails


def audit_e205(case_id: str) -> list[str]:
    cfg = _compose(C.override_id("g1a2_e205", case_id))
    fails = []
    for k, v in C.A2_GATE.items():
        if abs(float(cfg.get(k, float("nan"))) - v) > 1e-9:
            fails.append(f"{k}={cfg.get(k)}!=A2_GATE({v})")
    if float(cfg.get("leg_object_penalty_scale", 0.0)) != 2.0:
        fails.append(f"PRG leg_object_penalty_scale={cfg.get('leg_object_penalty_scale')}!=2.0")
    if not bool(cfg.get("cem_leg_gate_enabled", False)):
        fails.append("PRG cem_leg_gate_enabled!=true")
    if cfg.get("object_collision_sdf_mode") != "union":
        fails.append(f"object_collision_sdf_mode={cfg.get('object_collision_sdf_mode')}")
    if cfg.get("scene_name") != C.E205_SCENE:
        fails.append(f"scene_name={cfg.get('scene_name')}")
    return fails


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--audit", action="store_true", default=True)
    ap.add_argument("--no-audit", dest="audit", action="store_false")
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()

    sources = C.load_sources()
    if args.limit:
        sources = sources[: args.limit]

    for s in sources:
        write_e204(s["case_id"])
        write_e205(s["case_id"])
    print(f"wrote {len(sources)}x2 override YAMLs to {C.OVERRIDE_DIR.relative_to(C.REPO)}")

    if not args.audit:
        return 0
    all_fail = {}
    for s in sources:
        cid = s["case_id"]
        f4, f5 = audit_e204(cid), audit_e205(cid)
        if f4:
            all_fail[C.override_id("noprg_e204", cid)] = f4
        if f5:
            all_fail[C.override_id("g1a2_e205", cid)] = f5
    if all_fail:
        for oid, fails in all_fail.items():
            print(f"  FAIL {oid}: {'; '.join(fails)}")
        raise SystemExit(f"override audit FAILED for {len(all_fail)} configs")
    print(f"audit PASS: {len(sources)}x2 overrides single-variable arm contract verified")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
