#!/usr/bin/env python3
"""E215 P4: rot overrides, the single-variable compose audit, the frozen CEM queue.

Per built (case, rot variant), up to two Hydra files:

  ``core4d_{aug_task}.yaml``   the aug base task yaml.  Cloned from the case's
                               existing ``__aug_trans0`` base yaml (34 cases) with
                               only the ``task:`` line's variant suffix swapped
                               trans0->rot{k} -- so the contact-mask path and reward
                               defaults are byte-identical to the trans sibling that
                               was already validated single-variable.  Two cases
                               have no trans base yaml (E199/E202 trans was
                               infeasible) and fall back to cloning the dcv3 base.

  ``core4d_E215_{case}_aug_rot{k}_{token}.yaml``   the arm override (G1/G2/G3/G5):
                               ``defaults: [aug_base, _self_]`` + the arm's
                               ``prg_override_payload`` (e202 bucket proxy / e199
                               box rubber_hull).  G4 (noPRG) writes NO arm override
                               -- its ``+override`` is the aug base yaml and the
                               scene/negative-leg state comes from ``extra_overrides``
                               (E200 pattern, verified from config_act post-run).

The G1 groups (gravcomp) and G4/G5 force the effective scene via CLI
``extra_overrides`` on top of the arm override, matching how E210/E200 shipped.

Single-variable audit (plan247 C1): compose the FULL effective config (override
+ extra) for rot0 and rot1 and require the diff to be exactly ``{task}`` (plus
per-run ``output_dir``).  Where a trans0 sibling arm override exists (box_prg,
bucket_prg), additionally compose rot0 vs trans0 and require ``{task}``.  The
euler/hinge re-pick lives in the scene_act xml, not the composed config, so it
does not appear here (it is expected and reported as a scene-sha difference).

Usage:
    .venv/bin/python .../E215/build_aug_manifest.py --dry-run
    .venv/bin/python .../E215/build_aug_manifest.py [--skip-audit] [--freeze]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

_HERE = Path(__file__).resolve().parent
for _p in (_HERE, _HERE.parent / "E199", _HERE.parent / "E200", _HERE.parent / "E202"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

import e215_common as C  # noqa: E402

CEM_ROOT = C.rel(C.S6_DIR / "cem/full")
RENDER_ROOT = C.rel(C.S6_DIR / "render/full")
LOG_ROOT = "logs/E215/cem/full"

HEADER = "# @package _global_\n# Auto-generated by E215/build_aug_manifest.py.\n"
ALLOWED_DIFF_KEYS = frozenset({"task", "output_dir"})


def _yaml_scalar(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(str(v) for v in value) + "]"
    return str(value)


# --------------------------------------------------------------------------
# aug base task yaml (clone source: trans0 sibling, else dcv3 base)
# --------------------------------------------------------------------------
def clone_source(case: dict[str, str]) -> tuple[Path, str]:
    case_id = case["case_id"]
    trans0 = C.OVERRIDE_DIR / f"core4d_{C.aug_task_name(case_id, 'trans0')}.yaml"
    if trans0.is_file():
        return trans0, "trans0_sibling"
    dcv3 = C.OVERRIDE_DIR / f"core4d_{case['base_target_task']}.yaml"
    if dcv3.is_file():
        return dcv3, "dcv3_base"
    raise FileNotFoundError(
        f"{case_id}: neither trans0 aug base yaml nor dcv3 base override found "
        f"({trans0.name} / {dcv3.name})")


def write_aug_base_yaml(case: dict[str, str], aug_task: str) -> Path:
    src, kind = clone_source(case)
    out_lines, swapped = [], 0
    for line in src.read_text(encoding="utf-8").splitlines(keepends=True):
        if line.startswith("task:"):
            out_lines.append(f"task: {aug_task}\n")
            swapped += 1
        else:
            out_lines.append(line)
    if swapped != 1:
        raise AssertionError(f"expected exactly one `task:` line in {src.name}, found {swapped}")
    out_lines.insert(1, f"# E215: cloned from {src.name} ({kind}); `task:` retargeted at the rot aug dir.\n")
    path = C.OVERRIDE_DIR / f"core4d_{aug_task}.yaml"
    path.write_text("".join(out_lines), encoding="utf-8")
    return path


def mask_path_of(aug_base_yaml: Path) -> str:
    for line in aug_base_yaml.read_text(encoding="utf-8").splitlines():
        if line.strip().startswith("contact_hdmi_mask_path:"):
            return line.split(":", 1)[1].strip().strip('"')
    raise AssertionError(f"no contact_hdmi_mask_path in {aug_base_yaml.name}")


# --------------------------------------------------------------------------
# arm override (G1/G2/G3/G5)
# --------------------------------------------------------------------------
def prg_payload(case: dict[str, str], base_override_id: str) -> dict[str, Any]:
    spec = C.group_spec(case["case_id"])
    if spec["arm_override"] == "e202_prg":
        import e202_common as E202
        return E202.prg_override_payload(base_override_id)
    if spec["arm_override"] == "e199_prg":
        import e199_common as E199
        return E199.prg_override_payload(base_override_id)
    raise ValueError(f"{case['case_id']}: group {case['arm_group']} has no arm override")


def write_arm_override(case: dict[str, str], variant: str, base_override_id: str) -> Path:
    payload = prg_payload(case, base_override_id)
    lines = [HEADER, f"# E215 {case['arm_group']} arm; payload = "
             f"{case['arm_group'].split('_')[0]} prg_override_payload.\n",
             "defaults:\n"]
    for dep in payload["defaults"]:
        lines.append(f"- {dep}\n")
    for key, value in payload.items():
        if key == "defaults":
            continue
        if isinstance(value, list):
            if not value:
                lines.append(f"{key}: []\n")  # empty list must be [], not `key:` (=> null)
            else:
                lines.append(f"{key}:\n")
                for item in value:
                    lines.append(f"- {item}\n")
        else:
            lines.append(f"{key}: {_yaml_scalar(value)}\n")
    path = C.OVERRIDE_DIR / f"{C.override_name(case['case_id'], variant)}.yaml"
    path.write_text("".join(lines), encoding="utf-8")
    return path


def override_wiring(case: dict[str, str], variant: str, aug_base_yaml: Path) -> dict[str, Any]:
    """Return {override_id, override_path, extra_overrides} for this (case, variant)."""
    spec = C.group_spec(case["case_id"])
    extra_parts: list[str] = []
    if spec.get("extra_scene"):
        extra_parts.append(f"scene_name={spec['extra_scene']}")
    if spec.get("a2_gate"):
        import e200_common as E200
        extra_parts.append(E200.a2_overrides())
    extra = " ".join(extra_parts)

    if spec["arm_override"] == "base_only":  # G4 noPRG
        return {"override_id": aug_base_yaml.stem, "override_path": C.rel(aug_base_yaml),
                "extra_overrides": extra}
    arm = write_arm_override(case, variant, aug_base_yaml.stem)
    return {"override_id": arm.stem, "override_path": C.rel(arm), "extra_overrides": extra}


# --------------------------------------------------------------------------
# compose audit
# --------------------------------------------------------------------------
def compose(override_id: str, extra: str = "") -> dict[str, Any]:
    from hydra import compose as hydra_compose
    from hydra import initialize_config_dir
    from omegaconf import OmegaConf

    config_dir = str((C.REPO / "examples/config").resolve())
    overrides = [f"+override={override_id}"] + [tok for tok in extra.split() if tok]
    with initialize_config_dir(version_base=None, config_dir=config_dir):
        cfg = hydra_compose(config_name="default", overrides=overrides)
    out = OmegaConf.to_container(cfg, resolve=True)
    assert isinstance(out, dict)
    return out


def _diff_keys(a: dict[str, Any], b: dict[str, Any]) -> set[str]:
    keys = set(a) | set(b)
    return {k for k in keys if a.get(k, "__missing__") != b.get(k, "__missing__")}


def audit_case(case: dict[str, str], by_variant: dict[str, dict[str, Any]]) -> tuple[list[str], dict[str, Any]]:
    """rot0-vs-rot1 internal + (best-effort) rot0-vs-trans0 sibling."""
    fails: list[str] = []
    info: dict[str, Any] = {"case_id": case["case_id"], "arm_group": case["arm_group"]}
    try:
        composed = {v: compose(r["override_id"], r["extra_overrides"]) for v, r in by_variant.items()}
    except Exception as exc:  # noqa: BLE001
        return [f"{case['case_id']}: compose failed ({type(exc).__name__}: {exc})"], info

    if "rot0" in composed and "rot1" in composed:
        diff = _diff_keys(composed["rot0"], composed["rot1"])
        info["rot0_vs_rot1_diff"] = sorted(diff)
        unexpected = diff - ALLOWED_DIFF_KEYS
        if unexpected:
            fails.append(f"{case['case_id']}: rot0 vs rot1 unexpected diff {sorted(unexpected)}")
        if "task" not in diff:
            fails.append(f"{case['case_id']}: rot0/rot1 task identical -- variants collide")

    # rot0 vs trans0 sibling arm override, only where it exists on disk
    spec = C.group_spec(case["case_id"])
    if "rot0" in by_variant and spec["arm_override"] in ("e202_prg", "e199_prg"):
        token = spec["override_token"]
        trans_arm = None
        # E199/E202 trans arm override naming uses person{N}; try both p{N}/person{N}
        for cand in _trans_arm_override_candidates(case, token):
            if (C.OVERRIDE_DIR / f"{cand}.yaml").is_file():
                trans_arm = cand
                break
        if trans_arm:
            try:
                tcfg = compose(trans_arm, by_variant["rot0"]["extra_overrides"])
                diff = _diff_keys(composed["rot0"], tcfg)
                info["rot0_vs_trans0_override"] = trans_arm
                info["rot0_vs_trans0_diff"] = sorted(diff)
                unexpected = diff - ALLOWED_DIFF_KEYS
                if unexpected:
                    fails.append(f"{case['case_id']}: rot0 vs trans0 unexpected diff {sorted(unexpected)}")
            except Exception as exc:  # noqa: BLE001
                info["rot0_vs_trans0_override"] = f"compose_failed:{type(exc).__name__}"
        else:
            info["rot0_vs_trans0_override"] = "absent(skipped)"
    return fails, info


def _trans_arm_override_candidates(case: dict[str, str], token: str) -> list[str]:
    """E199/E202 trans PRG override ids to compare against (person{N} naming)."""
    case_id = case["case_id"]
    obj = case["object_key"]
    # case_id = {obj}_{date}_{seq}_p{N}; E199/E202 filenames use person{N}
    rest = case_id[len(obj) + 1:]
    stem, pn = rest.rsplit("_p", 1)
    exp = "E202" if obj.startswith("bucket") else "E199"
    return [f"core4d_{exp}_{obj}_{stem}_person{pn}_aug_trans0_{token}"]


# --------------------------------------------------------------------------
# manifest
# --------------------------------------------------------------------------
def artifact_paths(variant_id: str) -> dict[str, str]:
    return {
        "variant": variant_id,
        "result_npz": f"{CEM_ROOT}/{variant_id}.npz",
        "outdir_npz": f"{CEM_ROOT}/{variant_id}/trajectory_mjwp_act.npz",
        "config_act": f"{CEM_ROOT}/{variant_id}/config_act.yaml",
        "video": f"{RENDER_ROOT}/{variant_id}_full.mp4",
        "log": f"{LOG_ROOT}/{variant_id}.log",
    }


def tier_of(variant: str, first_rot0_of_object: bool) -> str:
    if variant == "rot0":
        return "P0" if first_rot0_of_object else "P1"
    return "P2"


def queue_order(rows: list[dict[str, Any]]) -> None:
    """Stratified prefix: within a tier, diagonal on (object, variant)."""
    tier_rank = {"P0": 0, "P1": 1, "P2": 2}
    objects = sorted({r["object_key"] for r in rows})
    obj_idx = {o: i for i, o in enumerate(objects)}
    var_idx = {"rot0": 0, "rot1": 1}
    n = max(len(objects), 1)
    rows.sort(key=lambda r: (
        tier_rank[r["tier"]],
        (obj_idx[r["object_key"]] + var_idx[r["aug_variant"]]) % n,
        obj_idx[r["object_key"]], r["case_id"], r["aug_variant"],
    ))
    for ordinal, row in enumerate(rows, 1):
        row["ordinal"] = ordinal


def build(*, dry_run: bool) -> tuple[list[dict[str, Any]], list[str], list[dict[str, Any]]]:
    arts = [r for r in C.read_tsv(C.ARTIFACTS_TSV) if r.get("status", "").startswith("built")]
    if not arts:
        raise SystemExit(f"no built rows in {C.rel(C.ARTIFACTS_TSV)}")

    budget = C.frozen_budget()
    rows: list[dict[str, Any]] = []
    blockers: list[str] = []
    first_rot0_seen: set[str] = set()

    # deterministic object order for the P0 "first rot0 per object" pick
    for art in sorted(arts, key=lambda r: (r["object_key"], r["case_id"], r["aug_variant"])):
        case = {"case_id": art["case_id"], "object_key": art["object_key"],
                "arm_group": art["arm_group"], "base_variant": art["base_variant"],
                "base_target_task": art["base_target_task"]}
        case_id, variant, aug_task = art["case_id"], art["aug_variant"], art["target_task"]

        if dry_run:
            base_yaml = C.OVERRIDE_DIR / f"core4d_{aug_task}.yaml"
        else:
            base_yaml = write_aug_base_yaml(case, aug_task)
        wiring = override_wiring(case, variant, base_yaml) if not dry_run else \
            {"override_id": "(dry)", "override_path": "", "extra_overrides": ""}

        mask = mask_path_of(base_yaml) if base_yaml.is_file() else ""
        variant_id = C.aug_variant_id(case_id, variant)
        is_first = variant == "rot0" and art["object_key"] not in first_rot0_seen
        if is_first:
            first_rot0_seen.add(art["object_key"])

        row: dict[str, Any] = {
            "ordinal": 0, "tier": tier_of(variant, is_first), "experiment": C.EXP_ID,
            "arm": art["arm_group"], "arm_group": art["arm_group"],
            "object_key": art["object_key"], "case_id": case_id, "aug_variant": variant,
            "aug_translation": art.get("aug_translation", ""),
            "aug_rotation_rad": art.get("aug_rotation_rad", ""),
            "base_variant": art["base_variant"], "base_target_task": art["base_target_task"],
            "target_task": aug_task, "target_scene": art["target_scene"],
            "trajectory": art["trajectory"], "trajectory_sha256": art["trajectory_sha256"],
            "contact_mask": mask, "contact_mask_sha256": C.sha256(mask) if mask and C.repo_path(mask).is_file() else "",
            "override_id": wiring["override_id"], "override_path": wiring["override_path"],
            "override_sha256": C.sha256(wiring["override_path"]) if wiring["override_path"] and C.repo_path(wiring["override_path"]).is_file() else "",
            "base_scene_act": art["base_scene_act"], "base_scene_sha256": art["base_scene_sha256"],
            "scene_act": art["scene_act"], "scene_name": art["scene_name"],
            "effective_scene_sha256": art["effective_scene_sha256"],
            "extra_overrides": wiring["extra_overrides"],
            "cem_samples": budget["num_samples"], "cem_opt_steps": budget["max_num_iterations"],
            "cem_seed": budget["seed"],
            "execution_mode": "production", "status": "", "failure_mode": "",
            "gpu_id": "", "wall_min": "", "updated_at": C.now(),
            "effective_retarget_variant": C.RETARGET_VARIANT,
            "gravcomp": int(bool(C.GROUPS[art["arm_group"]].get("gravcomp"))),
            "object_geom_count": art.get("object_geom_count", ""),
            "compiled_robot_object_pair_count": art.get("compiled_robot_object_pair_count", ""),
            "approach_yaw_deg_max": art.get("approach_yaw_deg_max", ""),
            "endpoint_yaw_deg": art.get("endpoint_yaw_deg", ""),
            "degraded_yaw": art.get("degraded_yaw", "0"),
            "approach_trans_offset_m_max": art.get("approach_trans_offset_m_max", ""),
            "orig_result_npz": "",
            **artifact_paths(variant_id),
        }
        for label, key in (("scene", "scene_act"), ("trajectory", "trajectory"),
                           ("target_scene", "target_scene")):
            if not C.repo_path(row[key]).is_file():
                blockers.append(f"{variant_id}:missing:{label}")
        if not dry_run and (not mask or not C.repo_path(mask).is_file()):
            blockers.append(f"{variant_id}:missing:contact_mask")
        if not dry_run and not C.repo_path(wiring["override_path"] or (base_yaml if False else "")).is_file():
            pass  # override_id may point at base yaml (noPRG); checked via override_path below
        rows.append(row)

    queue_order(rows)
    return rows, blockers, arts


def freeze(rows: list[dict[str, Any]]) -> dict[str, Any]:
    C.write_tsv(C.FROZEN_MANIFEST, rows, C.FIELDS)
    pairs = sorted(f"{r['case_id']}|{r['aug_variant']}" for r in rows)
    payload = {
        "experiment": C.EXP_ID, "run_id": C.RUN_ID, "frozen_at": C.now(), "n_rows": len(rows),
        "frozen_manifest": C.rel(C.FROZEN_MANIFEST),
        "frozen_manifest_sha256": C.sha256(C.FROZEN_MANIFEST),
        "priority_manifest": C.rel(C.PRIORITY_MANIFEST),
        "case_variant_set_sha256": C.sha256_text("\n".join(pairs)),
        "budget": C.frozen_budget(),
        "note": ("the runner may only write status/gpu_id/wall_min/failure_mode/updated_at, "
                 "never add or remove rows."),
    }
    C.write_json(C.FREEZE_JSON, payload)
    return payload


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--skip-audit", action="store_true")
    ap.add_argument("--freeze", action="store_true")
    args = ap.parse_args()

    rows, blockers, _arts = build(dry_run=args.dry_run)

    fails: list[str] = []
    audit_info: list[dict[str, Any]] = []
    if not args.skip_audit and not args.dry_run:
        by_case: dict[str, dict[str, dict[str, Any]]] = {}
        for row in rows:
            by_case.setdefault(row["case_id"], {})[row["aug_variant"]] = row
        for i, (case_id, by_variant) in enumerate(sorted(by_case.items()), 1):
            any_row = next(iter(by_variant.values()))
            case = {"case_id": case_id, "object_key": any_row["object_key"],
                    "arm_group": any_row["arm_group"], "base_variant": any_row["base_variant"],
                    "base_target_task": any_row["base_target_task"]}
            row_fails, info = audit_case(case, by_variant)
            fails.extend(row_fails)
            audit_info.append(info)
            if i % 10 == 0:
                print(f"  audited {i}/{len(by_case)} cases")

    for msg in blockers:
        print(f"[BLOCK] {msg}")
    for msg in fails:
        print(f"[AUDIT] {msg}")

    if args.dry_run:
        print(f"\ndry-run: would write {len(rows)} queue rows")
        for row in rows[:10]:
            print(f"  {row['ordinal']:3d} {row['tier']} {row['object_key']:9s} {row['aug_variant']:5s} "
                  f"{row['case_id']:32s} {row['arm_group']}")
        return 0

    C.write_tsv(C.PRIORITY_MANIFEST, rows, C.FIELDS)
    C.write_tsv(C.AUTHORITY_TSV, rows, C.FIELDS)

    by_object: dict[str, int] = {}
    by_group: dict[str, int] = {}
    by_tier: dict[str, int] = {}
    for row in rows:
        by_object[row["object_key"]] = by_object.get(row["object_key"], 0) + 1
        by_group[row["arm_group"]] = by_group.get(row["arm_group"], 0) + 1
        by_tier[row["tier"]] = by_tier.get(row["tier"], 0) + 1

    trans_audited = sum(1 for i in audit_info if isinstance(i.get("rot0_vs_trans0_diff"), list))
    C.write_json(C.OVERRIDE_AUDIT_JSON, {
        "experiment": C.EXP_ID, "generated_at": C.now(),
        "n_queue_rows": len(rows), "n_blockers": len(blockers), "n_audit_failures": len(fails),
        "blockers": blockers, "audit_failures": fails,
        "allowed_diff_keys": sorted(ALLOWED_DIFF_KEYS),
        "n_cases_audited": len(audit_info),
        "n_trans0_sibling_audited": trans_audited,
        "by_object": by_object, "by_arm_group": by_group, "by_tier": by_tier,
        "audit_detail": audit_info,
        "verdict": "pass" if not fails and not blockers else "fail",
    })

    if args.freeze and not fails and not blockers:
        fp = freeze(rows)
        print(f"frozen: {fp['n_rows']} rows, set sha {fp['case_variant_set_sha256'][:12]}")
    elif args.freeze:
        print("NOT frozen: audit/blockers present; fix before --freeze")

    print(f"\n{len(rows)} queue rows -> {C.rel(C.PRIORITY_MANIFEST)}")
    print(f"  by object {by_object}")
    print(f"  by group  {by_group}")
    print(f"  by tier   {by_tier}")
    print(f"  audit     {len(audit_info) - len(set(f.split(':')[0] for f in fails))}/{len(audit_info)} cases clean; "
          f"trans0-sibling audited {trans_audited}")
    return 1 if (fails or blockers) else 0


if __name__ == "__main__":
    raise SystemExit(main())
