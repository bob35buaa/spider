def now() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


def bool_text(value: bool) -> str:
    return "true" if value else "false"


def override_id(case_id: str, cell_id: str) -> str:
    return safe_id(f"core4d_E169_{case_id}_{cell_id}")


def write_override(source: dict[str, str], cell_id: str) -> Path:
    p_enabled, r_enabled, g_enabled = CELL_BITS[cell_id]
    payload = {
        "defaults": [source["override_id"], "_self_"],
        "scene_name": PHYSICS_SCENE_NAME if p_enabled else NO_PHYSICS_SCENE_NAME,
        "leg_object_penalty_scale": 2.0 if r_enabled else 0.0,
        "leg_object_penalty_margin_m": 0.02,
        "leg_object_penalty_geom_names": list(LOWER_BODY_GEOMS) if r_enabled else [],
        "leg_object_penalty_geom_ids": [],
        "leg_object_penalty_gate_source": "always",
        "leg_object_penalty_start_eval_time": 0.0,
        "leg_object_penalty_end_eval_time": 999.0,
        "cem_leg_gate_enabled": g_enabled,
        "cem_leg_gate_geom_names": list(LOWER_BODY_GEOMS) if g_enabled else [],
        "cem_leg_gate_geom_ids": [],
        "cem_leg_gate_min_sdf_m": 0.005,
        "cem_leg_gate_max_violation_pct": 0.02,
        "cem_leg_gate_hard_floor_m": -0.005,
        "cem_leg_gate_min_valid_frac": 0.02,
        "cem_leg_gate_fallback": "least_violation",
    }
    output = REPO / "examples/config/override" / f"{override_id(source['case_id'], cell_id)}.yaml"
    header = (
        "# @package _global_\n"
        "# Auto-generated by E169 factorial manifest builder.\n"
        f"# case_id: {source['case_id']}\n"
        f"# cell_id: {cell_id} (P={int(p_enabled)} R={int(r_enabled)} G={int(g_enabled)})\n"
    )
    output.write_text(
        header + yaml.safe_dump(payload, sort_keys=False, default_flow_style=False),
        encoding="utf-8",
    )
    return output


def normalized_config(config: Any) -> dict[str, Any]:
    value = OmegaConf.to_container(config, resolve=True)
    if not isinstance(value, dict):
        raise TypeError("composed Hydra config is not a mapping")
    return value


def audit_override(source: dict[str, str], cell_id: str, path: Path) -> dict[str, Any]:
    p_enabled, r_enabled, g_enabled = CELL_BITS[cell_id]
    config_dir = REPO / "examples/config"
    with initialize_config_dir(version_base=None, config_dir=str(config_dir.resolve())):
        baseline = compose(
            config_name="default", overrides=[f"+override={source['override_id']}"]
        )
        candidate = compose(
            config_name="default", overrides=[f"+override={path.stem}"]
        )
    base = normalized_config(baseline)
    actual = normalized_config(candidate)
    failures: list[str] = []
    for key in sorted(set(base) | set(actual)):
        if key in AXIS_FIELDS:
            continue
        if base.get(key) != actual.get(key):
            failures.append(f"non_axis_drift:{key}")
    expected = {
        "scene_name": PHYSICS_SCENE_NAME if p_enabled else NO_PHYSICS_SCENE_NAME,
        "leg_object_penalty_scale": 2.0 if r_enabled else 0.0,
        "leg_object_penalty_geom_names": list(LOWER_BODY_GEOMS) if r_enabled else [],
        "cem_leg_gate_enabled": g_enabled,
        "cem_leg_gate_geom_names": list(LOWER_BODY_GEOMS) if g_enabled else [],
        "cem_leg_gate_min_sdf_m": 0.005,
        "cem_leg_gate_max_violation_pct": 0.02,
        "cem_leg_gate_hard_floor_m": -0.005,
        "cem_leg_gate_min_valid_frac": 0.02,
        "cem_leg_gate_fallback": "least_violation",
    }
    for key, expected_value in expected.items():
        if actual.get(key) != expected_value:
            failures.append(f"axis_mismatch:{key}:{actual.get(key)!r}!={expected_value!r}")
    return {
        "case_id": source["case_id"],
        "cell_id": cell_id,
        "override_id": path.stem,
        "override_path": rel(path),
        "override_sha256": sha256(path),
        "audit_status": "pass" if not failures else "fail",
        "failures": ";".join(failures),
    }


def artifact_paths(variant: str, stage: str) -> dict[str, str]:
    subdir = "canary" if stage == "canary" else "full"
    suffix = "smoke" if stage == "canary" else "full"
    root = f"workspace/core4d/results/E169/cem/{subdir}"
    return {
        "result_npz": f"{root}/{variant}.npz",
        "outdir_npz": f"{root}/{variant}_outdir_{suffix}/trajectory_mjwp_act.npz",
        "config_act": f"{root}/{variant}_outdir_{suffix}/config_act.yaml",
        "video": f"workspace/core4d/results/E169/render/{subdir}/{variant}_{suffix}.mp4",
        "log": f"logs/E169/cem/{subdir}/{variant}.log",
    }


def build_rows() -> tuple[
    list[dict[str, Any]],
    list[dict[str, Any]],
    list[dict[str, Any]],
    list[dict[str, Any]],
]:
    sources = e168_rows()
    scene_audit = {
        row["case_id"]: row
        for row in __import__("csv").DictReader(
            (RESULTS / "scene_snapshot/scene_audit.tsv").open(
                "r", encoding="utf-8", newline=""
            ),
            delimiter="\t",
        )
    }
    analysis_rows: list[dict[str, Any]] = []
    audit_rows: list[dict[str, Any]] = []
    for case_id in CASES:
        source = sources[case_id]
        for cell_id, (p_enabled, r_enabled, g_enabled) in CELL_BITS.items():
            if cell_id == "B0":
                path = repo_path(source["override_path"])
                audit = {
                    "case_id": case_id,
                    "cell_id": cell_id,
                    "override_id": source["override_id"],
                    "override_path": source["override_path"],
                    "override_sha256": sha256(path),
                    "audit_status": "pass",
                    "failures": "",
                }
            else:
                path = write_override(source, cell_id)
                audit = audit_override(source, cell_id, path)
            audit_rows.append(audit)
            variant = safe_id(f"E169_{case_id}_{cell_id}")
            physical_scene = Path(source["scene_act"]).with_name(
                f"{PHYSICS_SCENE_NAME}.xml"
            )
            scene_act = rel(physical_scene) if p_enabled else source["scene_act"]
            paths = (
                {
                    "result_npz": source["result_npz"],
                    "outdir_npz": source["outdir_npz"],
                    "config_act": source["config_act"],
                    "video": source["video"],
                    "log": source["log"],
                }
                if cell_id == "B0"
                else artifact_paths(variant, "full")
            )
            analysis_rows.append(
                {
                    "ordinal": len(analysis_rows) + 1,
                    "variant": variant,
                    "case_id": case_id,
                    "sequence_key": source["sequence_key"],
                    "source_person": source["source_person"],
                    "object_key": source["object_key"],
                    "analysis_role": "control" if case_id == CONTROL_CASE else "failure",
                    "cell_id": cell_id,
                    "p_enabled": bool_text(p_enabled),
                    "r_enabled": bool_text(r_enabled),
                    "g_enabled": bool_text(g_enabled),
                    "reused_baseline": bool_text(cell_id == "B0"),
                    "target_task": source["target_task"],
                    "target_scene": source["target_scene"],
                    "trajectory": source["trajectory"],
                    "trajectory_sha256": scene_audit[case_id]["trajectory_sha256"],
                    "scene_act": scene_act,
                    "scene_name": PHYSICS_SCENE_NAME if p_enabled else NO_PHYSICS_SCENE_NAME,
                    "base_scene_sha256": scene_audit[case_id]["base_scene_sha256"],
                    "effective_scene_sha256": (
                        scene_audit[case_id]["physical_scene_sha256"]
                        if p_enabled
                        else scene_audit[case_id]["base_scene_sha256"]
                    ),
                    "contact_mask": source["contact_mask"],
                    "contact_mask_sha256": scene_audit[case_id]["contact_mask_sha256"],
                    "contact_mask_label": source["contact_mask_label"],
                    "retarget_variant_id": source["retarget_variant_id"],
                    "target_variant_id": source["target_variant_id"],
                    "hand_collision_variant_id": source["hand_collision_variant_id"],
                    "spider_method_id": source["spider_method_id"],
                    "override_id": audit["override_id"],
                    "override_path": audit["override_path"],
                    "override_sha256": audit["override_sha256"],
                    "config_audit_status": audit["audit_status"],
                    "execution_mode": "reused" if cell_id == "B0" else "production",
                    "execution_decision": "frozen_e168" if cell_id == "B0" else "a100_user_allowlist_0_1_2_3",
                    "preferred_pool": "a100",
                    "assigned_gpu": str(CASE_GPU[case_id]),
                    "gpu_id": source["gpu_id"] if cell_id == "B0" else "",
                    "status": "reused_complete" if cell_id == "B0" else "not_run",
                    "failure_mode": "",
                    **paths,
                    "updated_at": now(),
                }
            )
    if len(analysis_rows) != 32 or len(audit_rows) != 32:
        raise AssertionError("E169 factorial must contain 32 analysis/audit rows")
    if any(row["audit_status"] != "pass" for row in audit_rows):
        raise RuntimeError("E169 override audit failed")
    full_rows = [copy.deepcopy(row) for row in analysis_rows if row["cell_id"] != "B0"]
    canary_rows = []
    for row in analysis_rows:
        if row["cell_id"] != "PRG":
            continue
        canary = copy.deepcopy(row)
        canary["variant"] = f"{row['variant']}_canary"
        canary["execution_mode"] = "canary"
        canary["status"] = "not_run"
        canary.update(artifact_paths(canary["variant"], "canary"))
        canary_rows.append(canary)
    return analysis_rows, full_rows, canary_rows, audit_rows


def write_environment_manifest() -> None:
    output = RESULTS / "s0_environment/environment_manifest.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    git_commit = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=REPO, text=True, capture_output=True, check=True
    ).stdout.strip()
    payload = {
        "created_at": now(),
        "git_commit_before_e169_commit": git_commit,
        "remote_profile": "A100-8gpu",
        "remote_host": "61.172.170.106",
        "remote_root": "/home/dataset-assist-0/xiayb/workspace/spider",
        "allowed_gpus": [0, 1, 2, 3],
        "render_on_remote": False,
        "cases": list(CASES),
        "full_cells": list(FULL_CELLS),
    }
    output.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--stage", choices=("preflight",), default="preflight")
    parser.add_argument("--overwrite-scenes", action="store_true")
    args = parser.parse_args()
    build_all(overwrite=args.overwrite_scenes)
    analysis, full_rows, canary_rows, audit_rows = build_rows()
    SCRIPT_DIR.mkdir(parents=True, exist_ok=True)
    manifest_dir = RESULTS / "manifests"
    write_tsv(SCRIPT_DIR / "variants.tsv", analysis)
    write_tsv(manifest_dir / "factorial_analysis_manifest.tsv", analysis)
    write_tsv(manifest_dir / "cem_full_manifest.tsv", full_rows)
    write_tsv(manifest_dir / "cem_canary_manifest.tsv", canary_rows)
    write_tsv(RESULTS / "preflight/config_audit.tsv", audit_rows)
    write_environment_manifest()
    summary = {
        "created_at": now(),
        "status": "pass",
        "analysis_rows": len(analysis),
        "reused_baselines": sum(row["cell_id"] == "B0" for row in analysis),
        "new_full_rows": len(full_rows),
        "canary_rows": len(canary_rows),
        "cases": list(CASES),
        "cells": list(CELL_BITS),
        "assigned_gpus": CASE_GPU,
        "config_audit_pass": sum(row["audit_status"] == "pass" for row in audit_rows),
    }
    (RESULTS / "preflight/preflight_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
