#!/usr/bin/env python3
"""E202: build CEM overrides + the local 8-GPU priority manifest for bucket aug.

Input authority = e202_bucket_aug_artifacts.tsv (from build_augmented_tasks.py).
Per translation variant per case this:
  1. writes the aug base task Hydra yaml `core4d_{aug_task}.yaml` (copy of the
     historical dcv3 base yaml with task + 3cm mask swapped);
  2. writes the E202 PRG override `core4d_E202_{case}_aug_{trans}_PRG.yaml`
     (defaults -> aug base yaml; E174 leg gate/penalty + E178 union-SDF axes);
  3. emits a P1 priority-manifest row with the frozen E174/E178 full CEM budget
     (seed 0, 1024 samples, 32 opt steps) and SHA provenance.

The 27 orig baselines are NOT queued: reused from the E178 full-CEM rollouts
(status=reused_e178) and recorded only in the authority TSV for eval pairing.
Never overwrites the historical dcv3 / E174 / E178 yamls or scenes.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import e202_common as C  # noqa: E402

CEM_ROOT = "workspace/core4d/results/E202/s6_downstream/cem/full"
RENDER_ROOT = "workspace/core4d/results/E202/s6_downstream/render/full"


def base_task_override_id(aug_task: str) -> str:
    return C.safe_id(f"core4d_{aug_task}")


def write_base_task_yaml(base_task: str, aug_task: str, mask_rel: str) -> Path:
    src = C.OVERRIDE_DIR / f"core4d_{base_task}.yaml"
    if not src.is_file():
        raise FileNotFoundError(f"historical dcv3 base yaml missing: {src}")
    out = C.OVERRIDE_DIR / f"{base_task_override_id(aug_task)}.yaml"
    swapped: list[str] = []
    for line in src.read_text(encoding="utf-8").splitlines():
        if line.startswith("task:"):
            swapped.append(f"task: {aug_task}")
        elif line.startswith("contact_hdmi_mask_path:"):
            swapped.append(f'contact_hdmi_mask_path: "{mask_rel}"')
        else:
            swapped.append(line)
    header = ("# @package _global_\n"
              f"# E202 augmented base task yaml (copied from core4d_{base_task}.yaml).\n"
              f"# aug_task: {aug_task}\n")
    out.write_text(header + "\n".join(swapped) + "\n", encoding="utf-8")
    return out


def write_prg_override(case_id: str, aug_variant: str, base_override_id: str) -> Path:
    override_id = C.safe_id(f"core4d_E202_{case_id}_aug_{aug_variant}_PRG")
    out = C.OVERRIDE_DIR / f"{override_id}.yaml"
    header = "# @package _global_\n# Auto-generated by E202 build_aug_manifest.py.\n"
    out.write_text(header + yaml.safe_dump(C.prg_override_payload(base_override_id), sort_keys=False),
                   encoding="utf-8")
    return out


def artifact_paths(variant_id: str) -> dict[str, str]:
    return {
        "variant": variant_id,
        "result_npz": f"{CEM_ROOT}/{variant_id}.npz",
        "outdir_npz": f"{CEM_ROOT}/{variant_id}_outdir_full/trajectory_mjwp_act.npz",
        "config_act": f"{CEM_ROOT}/{variant_id}_outdir_full/config_act.yaml",
        "video": f"{RENDER_ROOT}/{variant_id}_full.mp4",
        "log": f"logs/E202/cem/full/{variant_id}.log",
    }


def reused_orig_row(case: dict[str, str]) -> dict[str, Any]:
    """A non-queued row recording the reused E178 orig full-CEM rollout (eval pairing)."""
    return {
        "ordinal": "", "tier": "P0", "experiment": "E202", "arm": "A0PRG_E178",
        "object_key": case["object_key"], "case_id": case["case_id"], "aug_variant": "orig",
        "aug_translation": "0,0,0", "aug_rotation_rad": "0",
        "base_target_task": case["base_target_task"], "target_task": case["base_target_task"],
        "target_scene": "", "trajectory": case["orig_trajectory"], "trajectory_sha256": "",
        "contact_mask": case["orig_contact_mask"], "contact_mask_sha256": "",
        "override_id": case["orig_override_id"], "override_path": "", "override_sha256": "",
        "base_scene_act": "", "base_scene_sha256": "",
        "scene_act": case["orig_scene_act"], "scene_name": case["e178_scene_name"],
        "effective_scene_sha256": "", "extra_overrides": "",
        "cem_samples": C.CEM_FULL_SAMPLES, "cem_opt_steps": C.CEM_FULL_OPT_STEPS, "cem_seed": C.CEM_SEED,
        "variant": Path(case["orig_result_npz"]).stem if case["orig_result_npz"] else "",
        "result_npz": case["orig_result_npz"], "outdir_npz": case["orig_outdir_npz"],
        "config_act": "", "video": "", "log": "",
        "gpu_id": "", "status": "reused_e178", "failure_mode": "",
        "execution_mode": "reused", "updated_at": C.now(),
    }


def build(artifacts: Path) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[str]]:
    rows_in = C.read_tsv(artifacts)
    if not rows_in:
        raise SystemExit(f"no artifact rows in {C.rel(artifacts)} -- run build_augmented_tasks.py first")
    queue_rows: list[dict[str, Any]] = []
    blockers: list[str] = []
    for art in rows_in:
        base_task = art["base_target_task"]
        aug_task = art["target_task"]
        aug_variant = art["aug_variant"]
        case_id = art["case_id"]
        mask_rel = art["contact_mask"]

        base_yaml = write_base_task_yaml(base_task, aug_task, mask_rel)
        override = write_prg_override(case_id, aug_variant, base_yaml.stem)
        variant_id = C.safe_id(f"E202_{case_id}_aug_{aug_variant}_PRG")

        row = {
            "tier": "P1", "experiment": "E202", "arm": "A0PRG_E178",
            "object_key": art["object_key"], "case_id": case_id, "aug_variant": aug_variant,
            "aug_translation": art.get("aug_translation", ""),
            "aug_rotation_rad": art.get("aug_rotation_rad", ""),
            "base_target_task": base_task, "target_task": aug_task,
            "target_scene": C.rel(C.TASK_ROOT / aug_task / "scene.xml"),
            "trajectory": art["trajectory"], "trajectory_sha256": art["trajectory_sha256"],
            "contact_mask": mask_rel, "contact_mask_sha256": art["contact_mask_sha256"],
            "override_id": override.stem, "override_path": C.rel(override),
            "override_sha256": C.sha256(override),
            "base_scene_act": art["base_scene_act"], "base_scene_sha256": art["base_scene_sha256"],
            "scene_act": art["scene_act"], "scene_name": C.SCENE_NAME,
            "effective_scene_sha256": art["effective_scene_sha256"],
            "object_geom_count": art.get("object_geom_count", ""),
            "compiled_robot_object_pair_count": art.get("compiled_robot_object_pair_count", ""),
            "extra_overrides": "",
            "cem_samples": C.CEM_FULL_SAMPLES, "cem_opt_steps": C.CEM_FULL_OPT_STEPS, "cem_seed": C.CEM_SEED,
            "execution_mode": "production", "status": "", "failure_mode": "", "gpu_id": "",
            "updated_at": C.now(),
            **artifact_paths(variant_id),
        }
        for label, key in (("scene", "scene_act"), ("trajectory", "trajectory"),
                           ("override", "override_path"), ("contact", "contact_mask"),
                           ("target_scene", "target_scene")):
            if not C.repo_path(row[key]).is_file():
                blockers.append(f"{variant_id}:missing:{label}")
        queue_rows.append(row)

    queue_rows.sort(key=lambda r: (r["object_key"], r["case_id"], r["aug_variant"]))
    for ordinal, row in enumerate(queue_rows, 1):
        row["ordinal"] = ordinal

    # authority = queued trans rows + reused-E178 orig rows (one per case, for eval pairing)
    orig_rows = [reused_orig_row(c) for c in C.load_e178_bucket_cases()
                 if c["case_id"] in {r["case_id"] for r in queue_rows}]
    authority_rows = queue_rows + orig_rows
    return queue_rows, authority_rows, blockers


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--artifacts", default="")
    args = parser.parse_args()

    artifacts = C.repo_path(args.artifacts) if args.artifacts else C.ARTIFACTS_TSV
    queue_rows, authority_rows, blockers = build(artifacts)
    fields = list(C.FIELDS)
    for extra in ("object_geom_count", "compiled_robot_object_pair_count"):
        if extra not in fields:
            fields.append(extra)
    C.write_tsv(C.FULL_MANIFEST, queue_rows, fields)
    C.write_tsv(C.AUTHORITY_TSV, authority_rows, fields)
    summary = {
        "created_at": C.now(), "queue_rows": len(queue_rows), "authority_rows": len(authority_rows),
        "by_object": {k: sum(r["object_key"] == k for r in queue_rows)
                      for k in sorted({r["object_key"] for r in queue_rows})},
        "by_case": len({r["case_id"] for r in queue_rows}),
        "reused_e178_orig": len(authority_rows) - len(queue_rows),
        "blockers": blockers, "manifest": C.rel(C.FULL_MANIFEST),
        "frozen_cem": {"seed": C.CEM_SEED, "samples": C.CEM_FULL_SAMPLES, "opt_steps": C.CEM_FULL_OPT_STEPS},
    }
    C.write_json(C.MANIFEST_DIR / "e202_manifest_summary.json", summary)
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 1 if blockers else 0


if __name__ == "__main__":
    raise SystemExit(main())
