#!/usr/bin/env python3
"""E208 P5: aug overrides, the V5e compose audit, and the frozen CEM queue.

Two Hydra files per aug task:

  ``core4d_{aug_task}.yaml``        E206's S5 base override with ONE line changed
                                    (``task:``).  Copying rather than regenerating
                                    keeps the contact-mask path pointing at E206's
                                    3 cm mask -- there is deliberately no second
                                    copy of that mask to drift from (F3: the aug
                                    variants share ``_original``'s trim window, so
                                    the mask is valid frame-for-frame).
  ``core4d_E208_{case}_aug_{v}_lowgeom_PRG.yaml``
                                    ``e206_common.PRG_OVERRIDES`` verbatim, by
                                    value.  Not re-typed, so the arm cannot drift
                                    from the baseline it is compared against.

**V5e** then composes the aug override and E206's own PRG override for the same
case and requires the difference to be exactly the task identity and what Hydra
derives from it.  This is the check that catches an aug run silently inheriting a
different reward, gate or SDF mode -- which would make any C4 delta unreadable.
The allowed set is closed: a new key appearing on either side is a failure, not a
warning.

The queue is ordered so that **every prefix is a stratified sample**: with 4
objects x 5 variants the first 20 rows cover all 20 cells exactly once, and
within a round a diagonal on (object + variant) keeps consecutive rows on
different objects *and* different variants.  Interrupting the queue at any point
therefore leaves a balanced design rather than a truncated one.  (plan238 gave
chair005 the head of each round as the only n=1 object; it is excluded now, so
that rule is gone with it.)

Also emits ``e208_aug_authority.tsv``: the aug rows plus one ``reused_e206`` row
per orig case, pointing at E206's PRG rollout.  Those rows are the C4 pairing
partners and are deliberately kept OUT of the priority manifest -- nothing about
them is to be re-run.

Usage:
    .venv/bin/python .../E208/build_aug_manifest.py --dry-run
    .venv/bin/python .../E208/build_aug_manifest.py
    ... --skip-audit          # write files without composing (fast iteration)
    ... --freeze              # also write the frozen copy + freeze.json
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

import e208_common as C  # noqa: E402

CEM_ROOT = C.rel(C.S6_DIR / "cem/full")
RENDER_ROOT = C.rel(C.S6_DIR / "render/full")
LOG_ROOT = "logs/E208/cem/full"

HEADER = "# @package _global_\n# Auto-generated by E208/build_aug_manifest.py.\n"

# V5e: keys that may differ between the composed aug config and the composed
# E206 PRG config for the same case.
#
# Measured 2026-09-05 across all 105 pairs, the observed difference is exactly
# ``{"task"}`` -- the trajectory, scene and mask paths are resolved from `task`
# at run time rather than materialised into the composed config, so they never
# show up here.  The set is therefore kept at what is actually true plus
# ``output_dir`` (passed on the CLI, so absent from a compose but legitimately
# per-run).  Deliberately NOT widened to the path keys: a path key appearing in
# this diff would mean something started pinning paths in the yaml, which is
# exactly the drift this gate exists to catch.
ALLOWED_DIFF_KEYS = frozenset({"task", "output_dir"})


def _yaml_scalar(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(str(v) for v in value) + "]"
    return str(value)


def e206_base_override(base_task: str) -> Path:
    src = C.E206_OVERRIDE_SRC / f"core4d_{base_task}.yaml"
    if not src.is_file():
        raise FileNotFoundError(f"E206 S5 base override missing: {src}")
    return src


def write_aug_base_yaml(base_task: str, aug_task: str) -> Path:
    """E206's base override with the task line retargeted at the aug dir.

    Everything else -- reward defaults, the ref_fk contact target, the 3 cm mask
    path, the camera -- is carried over byte-for-byte, so the aug run inherits
    E206's configuration by construction rather than by re-derivation.
    """
    src_text = e206_base_override(base_task).read_text(encoding="utf-8")
    out_lines, swapped = [], 0
    for line in src_text.splitlines(keepends=True):
        if line.startswith("task:"):
            out_lines.append(f"task: {aug_task}\n")
            swapped += 1
        else:
            out_lines.append(line)
    if swapped != 1:
        raise AssertionError(
            f"expected exactly one `task:` line in core4d_{base_task}.yaml, found {swapped}"
        )
    out_lines.insert(
        1, f"# E208: derived from core4d_{base_task}.yaml, `task:` retargeted at the aug dir.\n"
    )
    path = C.OVERRIDE_DIR / f"core4d_{aug_task}.yaml"
    path.write_text("".join(out_lines), encoding="utf-8")
    return path


def write_prg_override(case_id: str, variant: str, base_override_id: str) -> Path:
    lines = [
        HEADER,
        f"# E208 PRG arm on E206's hand-placed lowgeom proxy "
        f"(base reward {C.E206.BASE_REWARD_METHOD}); payload is e206_common.PRG_OVERRIDES.\n",
        "defaults:\n",
        f"- {base_override_id}\n",
        "- _self_\n",
    ]
    for key, value in C.PRG_OVERRIDES.items():
        lines.append(f"{key}: {_yaml_scalar(value)}\n")
    path = C.OVERRIDE_DIR / f"{C.override_name(case_id, variant)}.yaml"
    path.write_text("".join(lines), encoding="utf-8")
    return path


def compose(override_id: str) -> dict[str, Any]:
    from hydra import compose as hydra_compose
    from hydra import initialize_config_dir
    from omegaconf import OmegaConf

    config_dir = str((C.REPO / "examples/config").resolve())
    with initialize_config_dir(version_base=None, config_dir=config_dir):
        cfg = hydra_compose(config_name="default", overrides=[f"+override={override_id}"])
    out = OmegaConf.to_container(cfg, resolve=True)
    assert isinstance(out, dict)
    return out


def audit_row(row: dict[str, Any]) -> tuple[list[str], set[str]]:
    """V5e for one aug task, against E206's PRG override for the same case.

    Returns the failures and the keys that actually differed -- reporting the
    OBSERVED set matters, because passing only proves the diff sits inside
    ``ALLOWED_DIFF_KEYS``, not that the allowed set is tight.
    """
    fails: list[str] = []
    aug_id = row["override_id"]
    e206_id = C.E206.override_name(row["case_id"], "prg")
    try:
        aug_cfg = compose(aug_id)
        e206_cfg = compose(e206_id)
    except Exception as exc:
        return [f"{aug_id}: compose failed ({type(exc).__name__}: {exc})"], set()

    keys = set(aug_cfg) | set(e206_cfg)
    diff = {
        k for k in keys
        if aug_cfg.get(k, "__missing__") != e206_cfg.get(k, "__missing__")
    }
    unexpected = diff - ALLOWED_DIFF_KEYS
    if unexpected:
        detail = ", ".join(
            f"{k}={e206_cfg.get(k, '__missing__')!r}->{aug_cfg.get(k, '__missing__')!r}"
            for k in sorted(unexpected)
        )
        fails.append(f"{aug_id}: unexpected diff vs E206 PRG: {detail}")
    if "task" not in diff:
        fails.append(f"{aug_id}: task identical to E206 base -- the aug dir is not in play")

    if aug_cfg.get("scene_name") != C.SCENE_NAME:
        fails.append(f"{aug_id}: scene_name={aug_cfg.get('scene_name')!r}")
    # spider/config.py:69-79 is fail-closed on non-box geoms unless this is set;
    # it must be present explicitly, not inherited by luck.
    if aug_cfg.get("object_collision_sdf_mode") != "union":
        fails.append(
            f"{aug_id}: object_collision_sdf_mode={aug_cfg.get('object_collision_sdf_mode')!r}"
        )
    for k, v in C.E163_HAND_GATE.items():
        got = aug_cfg.get(k)
        if isinstance(v, bool):
            if bool(got) != v:
                fails.append(f"{aug_id}: {k}={got}!=E163({v})")
        elif got is None or abs(float(got) - float(v)) > 1e-9:
            fails.append(f"{aug_id}: {k}={got}!=E163({v})")
    return fails, diff


def artifact_paths(variant_id: str) -> dict[str, str]:
    return {
        "variant": variant_id,
        "result_npz": f"{CEM_ROOT}/{variant_id}.npz",
        "outdir_npz": f"{CEM_ROOT}/{variant_id}/trajectory_mjwp_act.npz",
        "config_act": f"{CEM_ROOT}/{variant_id}/config_act.yaml",
        "video": f"{RENDER_ROOT}/{variant_id}_full.mp4",
        "log": f"{LOG_ROOT}/{variant_id}.log",
    }


def queue_order(rows: list[dict[str, Any]]) -> None:
    """Order so every prefix is a stratified sample; assigns `ordinal` in place."""
    objects = sorted({r["object_key"] for r in rows})
    variants = [v for v, _ in C.BUILD_VARIANTS]
    obj_idx = {o: i for i, o in enumerate(objects)}
    var_idx = {v: i for i, v in enumerate(variants)}

    rank: dict[tuple[str, str], int] = {}
    for row in sorted(rows, key=lambda r: (r["object_key"], r["aug_variant"], r["case_id"])):
        cell = (row["object_key"], row["aug_variant"])
        row["_rank"] = rank.get(cell, 0)
        rank[cell] = row["_rank"] + 1

    n_var = max(len(variants), 1)
    rows.sort(key=lambda r: (
        r["_rank"],                                                    # round
        (obj_idx[r["object_key"]] + var_idx[r["aug_variant"]]) % n_var,  # diagonal
        obj_idx[r["object_key"]],
        var_idx[r["aug_variant"]],
        r["case_id"],
    ))
    for ordinal, row in enumerate(rows, 1):
        row["ordinal"] = ordinal
        row.pop("_rank", None)


def build(*, dry_run: bool) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[str]]:
    arts = [r for r in C.read_tsv(C.ARTIFACTS_TSV) if r.get("status", "").startswith("built")]
    if not arts:
        raise SystemExit(f"no built rows in {C.rel(C.ARTIFACTS_TSV)}")

    budget = C.frozen_budget()
    rows: list[dict[str, Any]] = []
    blockers: list[str] = []

    for art in arts:
        if C.is_excluded(art["object_key"]):
            continue
        case_id, variant = art["case_id"], art["aug_variant"]
        base_task, aug_task = art["base_target_task"], art["target_task"]

        if dry_run:
            base_yaml = C.OVERRIDE_DIR / f"core4d_{aug_task}.yaml"
            override = C.OVERRIDE_DIR / f"{C.override_name(case_id, variant)}.yaml"
        else:
            base_yaml = write_aug_base_yaml(base_task, aug_task)
            override = write_prg_override(case_id, variant, base_yaml.stem)

        variant_id = C.aug_variant_id(case_id, variant)
        offset = float(art["approach_trans_offset_m_max"])
        row: dict[str, Any] = {
            "ordinal": 0, "tier": "P0", "experiment": C.EXP_ID, "arm": C.ARM_ID.upper(),
            "object_key": art["object_key"], "case_id": case_id, "aug_variant": variant,
            "aug_translation": art.get("aug_translation", ""),
            "aug_rotation_rad": art.get("aug_rotation_rad", ""),
            "base_target_task": base_task, "target_task": aug_task,
            "target_scene": art["target_scene"],
            "trajectory": art["trajectory"], "trajectory_sha256": art["trajectory_sha256"],
            "contact_mask": art["contact_mask"], "contact_mask_sha256": art["contact_mask_sha256"],
            "override_id": override.stem, "override_path": C.rel(override),
            "override_sha256": C.sha256(override) if override.is_file() else "",
            "base_scene_act": art["base_scene_act"], "base_scene_sha256": art["base_scene_sha256"],
            "scene_act": art["scene_act"], "scene_name": C.SCENE_NAME,
            "effective_scene_sha256": art["effective_scene_sha256"],
            "extra_overrides": "",
            "cem_samples": budget["num_samples"], "cem_opt_steps": budget["max_num_iterations"],
            "cem_seed": budget["seed"],
            "execution_mode": "production", "status": "", "failure_mode": "",
            "gpu_id": "", "wall_min": "", "updated_at": C.now(),
            "pass": art.get("pass", ""),
            "effective_retarget_variant": art["effective_retarget_variant"],
            "source_retarget_variant_id": art["source_retarget_variant_id"],
            "rescue_state": art.get("rescue_state", ""), "rescue_reason": art.get("rescue_reason", ""),
            "object_geom_count": art["object_geom_count"],
            "compiled_robot_object_pair_count": art["compiled_robot_object_pair_count"],
            "orig_result_npz": art["orig_result_npz"],
            "f15_divergent": art.get("f15_divergent", "0"),
            "approach_trans_offset_m_max": round(offset, 6),
            "offset_band": C.offset_band(offset),
            **artifact_paths(variant_id),
        }
        for label, key in (("scene", "scene_act"), ("trajectory", "trajectory"),
                           ("contact", "contact_mask"), ("target_scene", "target_scene")):
            if not C.repo_path(row[key]).is_file():
                blockers.append(f"{variant_id}:missing:{label}")
        if not dry_run and not override.is_file():
            blockers.append(f"{variant_id}:missing:override")
        rows.append(row)

    queue_order(rows)

    # Authority table = the queue plus the orig partners it will be compared to.
    authority: list[dict[str, Any]] = [dict(r) for r in rows]
    seen: set[str] = set()
    for case in C.load_e208_cases():
        if C.is_excluded(case["object_key"]) or case["case_id"] in seen:
            continue
        seen.add(case["case_id"])
        authority.append({
            "ordinal": 0, "tier": "P0", "experiment": C.BASE_EXP_ID, "arm": C.ARM_ID.upper(),
            "object_key": case["object_key"], "case_id": case["case_id"], "aug_variant": "orig",
            "base_target_task": case["base_target_task"],
            "target_task": case["base_target_task"],
            "target_scene": case["orig_target_scene"],
            "trajectory": case["orig_trajectory"], "contact_mask": case["orig_contact_mask"],
            "scene_act": case["orig_scene_act"], "scene_name": C.SCENE_NAME,
            "override_id": C.E206.override_name(case["case_id"], "prg"),
            "cem_samples": budget["num_samples"], "cem_opt_steps": budget["max_num_iterations"],
            "cem_seed": budget["seed"],
            "execution_mode": "reused", "status": "reused_e206", "failure_mode": "",
            "result_npz": case["orig_result_npz"], "orig_result_npz": case["orig_result_npz"],
            "video": case["orig_video"],
            "source_retarget_variant_id": case["source_retarget_variant_id"],
            "effective_retarget_variant": case["source_retarget_variant_id"],
            "rescue_state": "", "rescue_reason": "",
            "approach_trans_offset_m_max": 0.0, "offset_band": "orig",
            "f15_divergent": "1" if case["case_id"] in C.F15_DIVERGENT_CASES else "0",
            "updated_at": C.now(),
        })
    return rows, authority, blockers


def freeze(rows: list[dict[str, Any]]) -> dict[str, Any]:
    C.write_tsv(C.FROZEN_MANIFEST, rows, C.FIELDS)
    pairs = sorted(f"{r['case_id']}|{r['aug_variant']}" for r in rows)
    payload = {
        "experiment": C.EXP_ID, "run_id": C.RUN_ID, "frozen_at": C.now(),
        "n_rows": len(rows),
        "frozen_manifest": C.rel(C.FROZEN_MANIFEST),
        "frozen_manifest_sha256": C.sha256(C.FROZEN_MANIFEST),
        "priority_manifest": C.rel(C.PRIORITY_MANIFEST),
        "case_variant_set_sha256": C.sha256_text("\n".join(pairs)),
        "scene_snapshot_manifest": C.rel(C.SNAPSHOT_DIR / "manifest.txt"),
        "scene_snapshot_manifest_sha256": (
            C.sha256(C.SNAPSHOT_DIR / "manifest.txt")
            if (C.SNAPSHOT_DIR / "manifest.txt").is_file() else ""
        ),
        "admission_json": C.rel(C.ADMISSION_JSON),
        "admission_sha256": C.sha256(C.ADMISSION_JSON) if C.ADMISSION_JSON.is_file() else "",
        "budget": C.frozen_budget(),
        "note": ("C7(d) re-checks case_variant_set_sha256 after P6; the runner may only "
                 "write status/gpu_id/wall_min/failure_mode/updated_at, never add or "
                 "remove rows."),
    }
    C.write_json(C.FREEZE_JSON, payload)
    return payload


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--skip-audit", action="store_true")
    ap.add_argument("--freeze", action="store_true",
                    help="write the frozen copy + freeze.json (run AFTER the scene snapshot)")
    args = ap.parse_args()

    rows, authority, blockers = build(dry_run=args.dry_run)

    fails: list[str] = []
    observed_diff: set[str] = set()
    if not args.skip_audit and not args.dry_run:
        for i, row in enumerate(rows, 1):
            row_fails, row_diff = audit_row(row)
            fails.extend(row_fails)
            observed_diff |= row_diff
            if i % 20 == 0:
                print(f"  V5e composed {i}/{len(rows)}")

    for msg in blockers:
        print(f"[BLOCK] {msg}")
    for msg in fails:
        print(f"[V5e] {msg}")

    if args.dry_run:
        print(f"\ndry-run: would write {len(rows)} queue rows "
              f"({len(authority) - len(rows)} reused_e206 partners)")
        for row in rows[:8]:
            print(f"  {row['ordinal']:3d} {row['object_key']:9s} {row['aug_variant']:7s} "
                  f"{row['case_id']:32s} band={row['offset_band']}")
        return 0

    C.write_tsv(C.PRIORITY_MANIFEST, rows, C.FIELDS)
    C.write_tsv(C.AUTHORITY_TSV, authority, C.FIELDS)

    by_object: dict[str, int] = {}
    by_variant: dict[str, int] = {}
    by_band: dict[str, int] = {}
    by_retarget: dict[str, int] = {}
    for row in rows:
        by_object[row["object_key"]] = by_object.get(row["object_key"], 0) + 1
        by_variant[row["aug_variant"]] = by_variant.get(row["aug_variant"], 0) + 1
        by_band[row["offset_band"]] = by_band.get(row["offset_band"], 0) + 1
        k = row["effective_retarget_variant"]
        by_retarget[k] = by_retarget.get(k, 0) + 1

    tier, action = C.l_tier(len(rows), C.eligible_potential())
    payload = {
        "experiment": C.EXP_ID, "check": "V5e", "generated_at": C.now(),
        "n_queue_rows": len(rows), "n_reused_e206": len(authority) - len(rows),
        "n_blockers": len(blockers), "n_v5e_failures": len(fails),
        "blockers": blockers, "v5e_failures": fails,
        "allowed_diff_keys": sorted(ALLOWED_DIFF_KEYS),
        "observed_diff_keys": sorted(observed_diff),
        "unused_allowed_diff_keys": sorted(ALLOWED_DIFF_KEYS - observed_diff),
        "excluded_objects": list(C.EXCLUDED_OBJECT_KEYS),
        "excluded_reason": C.EXCLUDED_REASON,
        "by_object": by_object, "by_variant": by_variant,
        "by_offset_band": by_band, "by_effective_retarget_variant": by_retarget,
        "l_tier": tier, "l_tier_action": action,
        "l_tier_denominator": C.eligible_potential(),
        "budget": C.frozen_budget(),
        "verdict": "pass" if not fails and not blockers else "fail",
    }
    C.write_json(C.OVERRIDE_AUDIT_JSON, payload)

    if args.freeze:
        fp = freeze(rows)
        print(f"frozen: {fp['n_rows']} rows, set sha {fp['case_variant_set_sha256'][:12]}")

    print(f"\n{len(rows)} queue rows -> {C.rel(C.PRIORITY_MANIFEST)}")
    print(f"  by object  {by_object}")
    print(f"  by variant {by_variant}")
    print(f"  by band    {by_band}")
    print(f"  retarget   {by_retarget}")
    print(f"  L tier     {tier} -- {action}")
    if observed_diff:
        print(f"  V5e diff   observed {sorted(observed_diff)} "
              f"(allowed but unused: {sorted(ALLOWED_DIFF_KEYS - observed_diff)})")
    print(f"  authority  {len(authority)} rows ({len(authority) - len(rows)} reused_e206)")
    print(f"  V5e        {len(rows) - len(set(f.split(':')[0] for f in fails))}/{len(rows)} pass"
          if fails else f"  V5e        {len(rows)}/{len(rows)} pass")
    return 1 if (fails or blockers) else 0


if __name__ == "__main__":
    raise SystemExit(main())
