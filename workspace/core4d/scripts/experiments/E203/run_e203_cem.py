#!/usr/bin/env python3
"""E203 orig CEM driver: full CEM on core4d_v2 (v2-human-motion) tasks.

Reuses the E199/E173 frozen PRG contract (rubber_hull hand + 16 lower-body
pairs + leg gate) but targets the ISOLATED core4d_v2 dataset tree and orig
(non-augmented) tasks. For each core4d_v2 dcv3 task it:

  1. builds the rubber_hull+PRG sidecar scene in the task dir (e199_common.build_prg_scene),
  2. writes a single-level Hydra override core4d_E203_<task>_PRG.yaml that pins
     `dataset_name: core4d_v2`, `scene_name: scene_act_E199_rubberHull_PRG`,
     the ref_fk contact target, the E203 3cm contact mask, and the PRG leg gate,
  3. runs examples/run_mjwp.py +override=... num_samples/max_num_iterations/seed.

Per-task failures (infeasible retarget missing, CEM crash) are recorded and
skipped; the batch continues.

Usage (smoke):
    uv run workspace/core4d/scripts/experiments/E203/run_e203_cem.py \
        --tasks dcv3_omnirt_v1_ref_fk_box001_20231003_1_039_p1 \
        --num-samples 64 --max-iterations 2 --smoke

Usage (full P1):
    uv run .../run_e203_cem.py --object-keys box001,box024   # defaults: 1024 x 32
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[5]
E199_DIR = REPO / "workspace/core4d/scripts/experiments/E199"
sys.path.insert(0, str(E199_DIR))
import e199_common as E199  # noqa: E402

# Redirect sidecar snapshots to E203 results (E199 module hardcodes its own).
E203_RESULTS = REPO / "workspace/core4d/results/E203"
E199.RESULTS = E203_RESULTS

DATASET = "core4d_v2"
TASK_ROOT = REPO / f"example_datasets/processed/{DATASET}/unitree_g1/humanoid_object"
OVERRIDE_DIR = REPO / "examples/config/override"
# S3 execution result root (contact masks live here).
S3_RESULT_ROOT = E203_RESULTS / "s3_retarget/omnirt_v1/ref_fk/results/omnirt_v1_ref_fk"
DEFAULT_BASE_REWARD = "core4d_E167_box004_082_p1_E167A"


def person_idx(task: str) -> int:
    return 0 if task.rstrip().endswith("_p1") else 1


def contact_mask_path(task: str) -> Path:
    return S3_RESULT_ROOT / "contact_masks" / task / "raw_contact_mask_3cm.npz"


def write_override(task: str, base_reward: str) -> Path:
    """Single-level E203 PRG override; dataset_name pinned to core4d_v2."""
    mask = contact_mask_path(task)
    lines = [
        "# @package _global_",
        "# Auto-generated by workspace/core4d/scripts/experiments/E203/run_e203_cem.py",
        f"# task: {task} (dataset={DATASET}, orig, PRG rubber_hull)",
        "defaults:",
        f"  - {base_reward}",
        "  - _self_",
        "",
        f"dataset_name: {DATASET}",
        f"task: {task}",
        f"scene_name: {E199.SCENE_NAME}",
        "",
        "contact_hdmi_target_source: ref_fk",
        'contact_hdmi_target_path: ""',
        "contact_hdmi_target_uses_eef_offset: true",
        'contact_hdmi_mask_source: "core4d_3cm"',
        f'contact_hdmi_mask_path: "{mask}"',
        f"contact_hdmi_mask_person_idx: {person_idx(task)}",
        'contact_hdmi_mask_time_axis: "auto"',
        "video_camera: auto",
        "",
        "# --- frozen E173/E199 PRG leg contract ---",
        f"leg_object_penalty_scale: {E199.LEG_OBJECT_PENALTY_SCALE}",
        f"leg_object_penalty_margin_m: {E199.LEG_OBJECT_PENALTY_MARGIN_M}",
        f"leg_object_penalty_geom_names: {list(E199.LOWER_BODY_GEOMS)}",
        "leg_object_penalty_geom_ids: []",
        "leg_object_penalty_gate_source: always",
        "leg_object_penalty_start_eval_time: 0.0",
        "leg_object_penalty_end_eval_time: 999.0",
        "cem_leg_gate_enabled: true",
        f"cem_leg_gate_geom_names: {list(E199.LOWER_BODY_GEOMS)}",
        "cem_leg_gate_geom_ids: []",
        f"cem_leg_gate_min_sdf_m: {E199.CEM_LEG_GATE_MIN_SDF_M}",
        f"cem_leg_gate_max_violation_pct: {E199.CEM_LEG_GATE_MAX_VIOLATION_PCT}",
        f"cem_leg_gate_hard_floor_m: {E199.CEM_LEG_GATE_HARD_FLOOR_M}",
        f"cem_leg_gate_min_valid_frac: {E199.CEM_LEG_GATE_MIN_VALID_FRAC}",
        f"cem_leg_gate_fallback: {E199.CEM_LEG_GATE_FALLBACK}",
        "",
    ]
    override_id = f"core4d_E203_{task}_PRG"
    path = OVERRIDE_DIR / f"{override_id}.yaml"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def prepare_one(task: str, *, num_samples: int, max_iters: int, seed: int,
                base_reward: str) -> dict:
    """Build PRG sidecar + override for one task. Returns dict with status and
    (if ready) 'cmd'. Does NOT run CEM."""
    task_dir = TASK_ROOT / task
    scene_act = task_dir / "scene_act.xml"
    trajectory = task_dir / "0/trajectory_kinematic.npz"
    result = {"task": task, "status": "", "note": ""}
    if not scene_act.is_file() or not trajectory.is_file():
        result["status"] = "skip_missing_task"
        result["note"] = f"scene_act={scene_act.is_file()} traj={trajectory.is_file()}"
        return result
    if not contact_mask_path(task).is_file():
        result["status"] = "skip_missing_mask"
        return result
    if (task_dir / "0/trajectory_mjwp_act.npz").is_file() and os.environ.get("E203_CEM_FORCE", "0") != "1":
        result["status"] = "skip_already_done"
        return result
    try:
        prg = E199.build_prg_scene(task, scene_act, trajectory, overwrite=True)
        result["prg_scene"] = prg["physical_scene"]
    except Exception as e:  # noqa: BLE001
        result["status"] = "prg_scene_error"
        result["note"] = str(e)[:300]
        return result
    override_id = f"core4d_E203_{task}_PRG"
    write_override(task, base_reward)
    result["cmd"] = [
        str(E199.SPIDER_PYTHON_BIN), "-u", "examples/run_mjwp.py",
        f"+override={override_id}", "video_camera=auto",
        f"seed={seed}", f"num_samples={num_samples}", f"max_num_iterations={max_iters}",
    ]
    result["status"] = "ready"
    return result


def cem_env(gpu: str | None) -> dict:
    env = dict(os.environ)
    env.setdefault("MUJOCO_GL", os.environ.get("E203_MUJOCO_GL", "egl"))
    if os.environ.get("E203_TORCH_COMPILE", "0") != "1":
        env["TORCHDYNAMO_DISABLE"] = "1"
    if gpu is not None:
        env["CUDA_VISIBLE_DEVICES"] = gpu
    env["PYTHONUNBUFFERED"] = "1"
    return env


def run_one(task: str, *, num_samples: int, max_iters: int, seed: int,
            base_reward: str, log_dir: Path, dry_run: bool) -> dict:
    result = prepare_one(task, num_samples=num_samples, max_iters=max_iters,
                         seed=seed, base_reward=base_reward)
    if result["status"] != "ready":
        return result
    cmd = result["cmd"]
    result["command"] = " ".join(cmd)
    if dry_run:
        result["status"] = "dry_run"
        return result
    log_dir.mkdir(parents=True, exist_ok=True)
    log_path = log_dir / f"{task}.log"
    env = cem_env(None)
    with open(log_path, "w") as f:
        f.write(f"# command={' '.join(cmd)} (MUJOCO_GL={env['MUJOCO_GL']})\n\n")
        f.flush()
        rc = subprocess.run(cmd, cwd=REPO, stdout=f, stderr=subprocess.STDOUT, env=env).returncode
    result["status"] = "cem_ok" if rc == 0 else f"cem_fail_rc{rc}"
    result["log"] = str(log_path)
    return result


def run_parallel(tasks: list[str], *, gpus: list[str], max_per_gpu: int,
                 num_samples: int, max_iters: int, seed: int, base_reward: str,
                 log_dir: Path) -> list[dict]:
    """Prepare all tasks, then run CEM across a GPU pool (one slot = one GPU)."""
    import time
    log_dir.mkdir(parents=True, exist_ok=True)
    prepared, results = [], []
    for task in tasks:
        r = prepare_one(task, num_samples=num_samples, max_iters=max_iters,
                        seed=seed, base_reward=base_reward)
        if r["status"] == "ready":
            prepared.append(r)
        else:
            print(f"   prep {task} -> {r['status']} {r.get('note','')}", flush=True)
            results.append(r)
    slots = [(g, s) for g in gpus for s in range(max_per_gpu)]
    running = {}  # slot -> (proc, result, fh)
    pending = list(prepared)
    while pending or running:
        for slot in list(slots):
            if not pending:
                break
            if slot in running:
                continue
            r = pending.pop(0)
            gpu = slot[0]
            fh = open(log_dir / f"{r['task']}.log", "w")
            fh.write(f"# gpu={gpu} command={' '.join(r['cmd'])}\n\n"); fh.flush()
            proc = subprocess.Popen(r["cmd"], cwd=REPO, stdout=fh,
                                    stderr=subprocess.STDOUT, env=cem_env(gpu))
            r["gpu"] = gpu
            running[slot] = (proc, r, fh)
            print(f"   launch {r['task']} on gpu {gpu} ({len(pending)} pending)", flush=True)
        done = [(slot, v) for slot, v in running.items() if v[0].poll() is not None]
        for slot, (proc, r, fh) in done:
            fh.close()
            r["status"] = "cem_ok" if proc.returncode == 0 else f"cem_fail_rc{proc.returncode}"
            r["log"] = str(log_dir / f"{r['task']}.log")
            r.pop("cmd", None)
            print(f"   done {r['task']} -> {r['status']}", flush=True)
            results.append(r)
            del running[slot]
        if running and not done:
            time.sleep(15)
    return results


def enumerate_tasks(object_keys: list[str]) -> list[str]:
    tasks = []
    for d in sorted(TASK_ROOT.glob("dcv3_*")):
        if not (d / "scene_act.xml").is_file():
            continue
        name = d.name
        if object_keys and not any(f"_{ok}_" in name for ok in object_keys):
            continue
        tasks.append(name)
    return tasks


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tasks", default="", help="comma-separated dcv3 task names")
    ap.add_argument("--object-keys", default="", help="comma-separated object keys (enumerate core4d_v2 tasks)")
    ap.add_argument("--num-samples", type=int, default=E199.CEM_FULL_SAMPLES)
    ap.add_argument("--max-iterations", type=int, default=E199.CEM_FULL_OPT_STEPS)
    ap.add_argument("--seed", type=int, default=E199.CEM_SEED)
    ap.add_argument("--base-reward", default=DEFAULT_BASE_REWARD)
    ap.add_argument("--out-dir", type=Path, default=E203_RESULTS / "s6_downstream/cem")
    ap.add_argument("--gpus", default="", help="comma-separated GPU ids for parallel dispatch (e.g. 0,1,..,7); empty=serial")
    ap.add_argument("--max-per-gpu", type=int, default=1)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--smoke", action="store_true", help="tag logs as smoke")
    args = ap.parse_args()

    if args.tasks:
        tasks = [t.strip() for t in args.tasks.split(",") if t.strip()]
    else:
        keys = [k.strip().lower() for k in args.object_keys.split(",") if k.strip()]
        tasks = enumerate_tasks(keys)
    if not tasks:
        print("no tasks", file=sys.stderr)
        return 2

    log_dir = args.out_dir / ("smoke" if args.smoke else "full")
    gpus = [g.strip() for g in args.gpus.split(",") if g.strip()]
    if gpus and not args.dry_run:
        print(f"parallel dispatch over gpus={gpus} max_per_gpu={args.max_per_gpu} ({len(tasks)} tasks)", flush=True)
        results = run_parallel(tasks, gpus=gpus, max_per_gpu=args.max_per_gpu,
                               num_samples=args.num_samples, max_iters=args.max_iterations,
                               seed=args.seed, base_reward=args.base_reward, log_dir=log_dir)
    else:
        results = []
        for i, task in enumerate(tasks):
            print(f"[{i+1}/{len(tasks)}] {task}", flush=True)
            r = run_one(task, num_samples=args.num_samples, max_iters=args.max_iterations,
                        seed=args.seed, base_reward=args.base_reward, log_dir=log_dir,
                        dry_run=args.dry_run)
            print(f"   -> {r['status']} {r.get('note','')}", flush=True)
            results.append(r)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    summary = args.out_dir / ("e203_cem_smoke_summary.json" if args.smoke else "e203_cem_summary.json")
    summary.write_text(json.dumps(results, indent=2), encoding="utf-8")
    import collections
    counts = collections.Counter(r["status"] for r in results)
    print("STATUS COUNTS:", dict(counts))
    print("summary ->", summary)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
