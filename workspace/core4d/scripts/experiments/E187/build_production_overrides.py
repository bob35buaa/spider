#!/usr/bin/env python3
"""Generate and audit the 22 opt-in E187 production overrides."""

from __future__ import annotations

import hashlib
import json
import os
import tempfile
from pathlib import Path
from typing import Any

import yaml
from hydra import compose, initialize_config_dir
from omegaconf import OmegaConf

REPO = Path(__file__).resolve().parents[5]
E186_SCENES = (
    REPO
    / "workspace/core4d/results/E186/s2_compound_physics/compound_scene_manifest.tsv"
)
LOCK = (
    REPO / "workspace/core4d/results/E187/s2_canonical_grid_sdf/reward_grid_lock.json"
)
OVERRIDE_DIR = REPO / "examples/config/override"
OUTPUT = REPO / "workspace/core4d/results/E187/s3_prg_audit/production_overrides.json"
METHOD_ID = "E187_canonical_distance_continuation_reward_r1"
ALLOWED_EFFECTIVE_DIFF = {
    "surface_band_score_mode",
    "surface_band_continuation_far_weight",
    "surface_band_continuation_near_weight",
    "surface_band_continuation_far_scale_m",
    "surface_band_continuation_near_scale_m",
    "surface_band_continuation_smooth_delta_m",
    "object_distance_manifest",
    "object_distance_error_bound_m",
}


def sha256(path: Path) -> str:
    """Return a streaming SHA-256 digest."""
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def read_rows() -> list[dict[str, str]]:
    """Read the E186 compound manifest without changing row order."""
    import csv

    with E186_SCENES.open(encoding="utf-8", newline="") as stream:
        rows = list(csv.DictReader(stream, delimiter="\t"))
    if len(rows) != 22 or len({row["case_id"] for row in rows}) != 22:
        raise RuntimeError("E186 production authority is not keep22")
    return rows


def relative(path: Path) -> str:
    """Render a lexical repository-relative path."""
    return path.absolute().relative_to(REPO.absolute()).as_posix()


def override_id(case_id: str) -> str:
    """Return the unique E187 opt-in Hydra override ID."""
    return f"core4d_E187_{case_id}_distanceContinuation"


def override_payload(row: dict[str, str], lock: dict[str, Any]) -> dict[str, Any]:
    """Build the exact allowed delta over one E186 production override."""
    selected = lock["objects"][row["object_key"]]
    reward = lock["reward"]
    return {
        "defaults": [row["override_id"], "_self_"],
        "surface_band_score_mode": reward["mode"],
        "surface_band_continuation_far_weight": reward["far_weight"],
        "surface_band_continuation_near_weight": reward["near_weight"],
        "surface_band_continuation_far_scale_m": reward["far_scale_m"],
        "surface_band_continuation_near_scale_m": reward["near_scale_m"],
        "surface_band_continuation_smooth_delta_m": reward["smooth_delta_m"],
        "object_distance_manifest": selected["grid_manifest"]["path"],
        "object_distance_expected_asset_sha256": json.loads(
            (REPO / selected["grid_manifest"]["path"]).read_text(encoding="utf-8")
        )["source"]["candidate_asset_sha256"],
        "object_distance_error_bound_m": selected["epsilon_grid_m"],
    }


def override_text(payload: dict[str, Any]) -> str:
    """Serialize one deterministic generated override."""
    header = (
        "# @package _global_\n# Auto-generated by E187 build_production_overrides.py.\n"
    )
    return header + yaml.safe_dump(payload, sort_keys=False)


def effective_config(override: str) -> dict[str, Any]:
    """Compose one Hydra override into its resolved global config."""
    config_dir = (REPO / "examples/config").resolve()
    with initialize_config_dir(version_base=None, config_dir=str(config_dir)):
        payload = OmegaConf.to_container(
            compose(config_name="default", overrides=[f"+override={override}"]),
            resolve=True,
        )
    if not isinstance(payload, dict):
        raise RuntimeError("Hydra effective config is not a dictionary")
    return payload


def write_immutable(path: Path, payload: bytes) -> None:
    """Create an override/evidence artifact or verify byte identity."""
    if path.exists():
        if path.read_bytes() != payload:
            raise RuntimeError(f"immutable E187 production artifact mismatch: {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(payload)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def build(*, write: bool) -> dict[str, Any]:
    """Build, compose, and whitelist all 22 overrides."""
    lock = json.loads(LOCK.read_text(encoding="utf-8"))
    if lock.get("status") != "FROZEN" or lock.get("experiment_id") != "E187":
        raise RuntimeError("reward/grid lock is not frozen")
    output_rows = []
    for row in read_rows():
        base_path = REPO / row["override_path"]
        if sha256(base_path) != row["override_sha256"]:
            raise RuntimeError(f"E186 override changed: {base_path}")
        identity = override_id(row["case_id"])
        path = OVERRIDE_DIR / f"{identity}.yaml"
        text = override_text(override_payload(row, lock))
        if write:
            write_immutable(path, text.encode())
        elif path.exists() and path.read_text(encoding="utf-8") != text:
            raise RuntimeError(f"existing E187 override differs: {path}")
        if not path.is_file() and not write:
            continue
        baseline = effective_config(row["override_id"])
        candidate = effective_config(identity)
        changed = {
            key: {"baseline": baseline.get(key), "candidate": candidate.get(key)}
            for key in sorted(set(baseline) | set(candidate))
            if baseline.get(key) != candidate.get(key)
        }
        unexpected = sorted(set(changed) - ALLOWED_EFFECTIVE_DIFF)
        if (
            unexpected
            or candidate["surface_band_score_mode"] != "distance_continuation"
        ):
            raise RuntimeError(
                f"{row['case_id']}: E187 effective config drift: {unexpected}"
            )
        selected = lock["objects"][row["object_key"]]
        if (
            candidate["scene_name"] != baseline["scene_name"]
            or candidate["object_collision_sdf_mode"]
            != baseline["object_collision_sdf_mode"]
            or candidate["object_distance_manifest"]
            != selected["grid_manifest"]["path"]
            or float(candidate["object_distance_error_bound_m"])
            != float(selected["epsilon_grid_m"])
        ):
            raise RuntimeError(f"{row['case_id']}: P/grid effective contract mismatch")
        output_rows.append(
            {
                "ordinal": len(output_rows) + 1,
                "case_id": row["case_id"],
                "object_key": row["object_key"],
                "source_override_id": row["override_id"],
                "source_override_sha256": row["override_sha256"],
                "override_id": identity,
                "override_path": relative(path),
                "override_sha256": sha256(path),
                "scene_name": candidate["scene_name"],
                "scene_sha256": row["effective_scene_sha256"],
                "grid_manifest": candidate["object_distance_manifest"],
                "grid_manifest_sha256": selected["grid_manifest"]["sha256"],
                "epsilon_grid_m": candidate["object_distance_error_bound_m"],
                "effective_changed_fields": changed,
                "status": "PASS",
            }
        )
    if write and len(output_rows) != 22:
        raise RuntimeError("E187 production overrides did not close 22 rows")
    payload = {
        "schema": "e187_production_overrides_v1",
        "experiment_id": "E187",
        "stage": "A2_S3_PRODUCTION_OVERRIDES",
        "status": "PASS" if len(output_rows) == 22 else "PENDING_GENERATION",
        "method_id": METHOD_ID,
        "gate0_technical_status": "FAIL",
        "progression_authority": "USER_WAIVED",
        "reward_grid_lock": {"path": relative(LOCK), "sha256": sha256(LOCK)},
        "row_count": len(output_rows),
        "allowed_effective_diff": sorted(ALLOWED_EFFECTIVE_DIFF),
        "rows": output_rows,
    }
    if write:
        encoded = (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode()
        write_immutable(OUTPUT, encoded)
    return payload


def main() -> int:
    """Generate and freeze the 22-row production override manifest."""
    payload = build(write=True)
    print(json.dumps(payload, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
