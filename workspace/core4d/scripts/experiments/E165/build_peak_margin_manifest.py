def rel(path: str | Path) -> str:
    if not path:
        return ""
    p = Path(path)
    try:
        return str(p.resolve().relative_to(REPO.resolve()))
    except Exception:
        return str(path)


def repo_path(path: str | Path) -> Path:
    p = Path(path)
    return p if p.is_absolute() else REPO / p


def read_tsv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def write_tsv(path: Path, rows: list[dict[str, Any]], fields: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields, delimiter="\t", lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: "" if row.get(field) is None else row.get(field, "") for field in fields})


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def git_head() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO, text=True).strip()
    except Exception:
        return "unknown"


def variant_for(case_id: str) -> str:
    return f"E165D_{case_id}_{METHOD_GROUP}"


def result_paths(case_id: str, stage: str = "full") -> tuple[str, str, str]:
    variant = variant_for(case_id)
    root = CEM_ROOT / stage
    return (
        rel(root / f"{variant}.npz"),
        rel(root / f"{variant}_outdir_{stage}/trajectory_mjwp_act.npz"),
        rel(root / f"{variant}_{stage}.mp4"),
    )


def full_artifacts_complete(case_id: str) -> bool:
    variant = variant_for(case_id)
    root = CEM_ROOT / "full"
    return (
        (root / f"{variant}.npz").is_file()
        and (root / f"{variant}_full.mp4").is_file()
        and (root / f"{variant}_outdir_full/trajectory_mjwp_act.npz").is_file()
        and (root / f"{variant}_outdir_full/config_act.yaml").is_file()
    )


def write_override(row: dict[str, Any]) -> str:
    path = OVERRIDE_ROOT / f"core4d_{row['variant']}.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    base_stem = Path(row["base_override"]).stem
    lines = [
        "# @package _global_",
        "# Auto-generated by workspace/core4d/scripts/experiments/E165/build_peak_margin_manifest.py.",
        f"# E165-D peak-margin rerank case={row['short_case_id']}.",
        "defaults:",
        f"  - {base_stem}",
        "  - _self_",
        "",
        "cem_peak_margin_enabled: true",
        f"cem_peak_margin_ee_threshold_m: {EE_THRESHOLD_M:.6f}",
        f"cem_peak_margin_anchor_threshold_m: {ANCHOR_THRESHOLD_M:.6f}",
        f"cem_peak_margin_buffer_m: {BUFFER_M:.6f}",
        f"cem_peak_margin_min_valid_frac: {MIN_VALID_FRAC:.6f}",
        f"cem_peak_margin_w_ee: {W_EE:.6f}",
        f"cem_peak_margin_w_anchor: {W_ANCHOR:.6f}",
        f"cem_peak_margin_w_posture: {W_POSTURE:.6f}",
        f"cem_peak_margin_lambda: {LAMBDA:.6f}",
        'cem_peak_margin_ee_body_names: ["left_ankle_roll_link", "right_ankle_roll_link", "left_wrist_yaw_link", "right_wrist_yaw_link"]',
        "cem_peak_margin_ee_body_ids: []",
        "cem_peak_margin_anchor_body_name: torso_link",
        "cem_peak_margin_anchor_body_id: -1",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return rel(path)


