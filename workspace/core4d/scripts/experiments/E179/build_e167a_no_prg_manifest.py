def semantic_xml(path: Path) -> bytes:
    return ET.tostring(ET.parse(path).getroot())


def yaml_payload(base_override: str) -> dict[str, Any]:
    return {
        "defaults": [base_override, "_self_"],
        "scene_name": C.SCENE_NAME,
    }


def write_override(row: dict[str, str]) -> Path:
    override_id = C.safe_id(
        f"core4d_E179_{row['case_id']}_E167A_noPRG"
    )
    output = C.OVERRIDE_DIR / f"{override_id}.yaml"
    header = (
        "# @package _global_\n"
        "# Auto-generated by E179 build_e167a_no_prg_manifest.py.\n"
        "# E167A z-only body tracking; E170 PRG intentionally absent.\n"
    )
    output.write_text(
        header
        + yaml.safe_dump(
            yaml_payload(row["dcv3_override_id"]),
            sort_keys=False,
        ),
        encoding="utf-8",
    )
    return output


def compose_config(override_id: str) -> dict[str, Any]:
    with initialize_config_dir(
        version_base=None,
        config_dir=str((C.REPO / "examples/config").resolve()),
    ):
        config = compose(
            config_name="default",
            overrides=[f"+override={override_id}"],
        )
    return dict(
        OmegaConf.to_container(config, resolve=True)  # type: ignore[arg-type]
    )


def audit_override(
    row: dict[str, str],
    output: Path,
    expected_profile: dict[str, Any],
) -> dict[str, Any]:
    source = compose_config(row["dcv3_override_id"])
    candidate = compose_config(output.stem)
    failures = []
    all_keys = sorted(set(source) | set(candidate))
    drift = {
        key: {"source": source.get(key), "candidate": candidate.get(key)}
        for key in all_keys
        if key != "scene_name"
        and source.get(key) != candidate.get(key)
    }
    if drift:
        failures.append("non_scene_config_drift")
    if candidate.get("scene_name") != C.SCENE_NAME:
        failures.append("scene_name_mismatch")
    override_doc = yaml.safe_load(output.read_text(encoding="utf-8"))
    leaked_override_fields = sorted(
        set(override_doc) & set(C.PRG_CONFIG_FIELDS)
    )
    if leaked_override_fields:
        failures.append("prg_override_field_leak")
    composed_prg_fields = sorted(
        key for key in C.PRG_CONFIG_FIELDS if key in candidate
    )
    if composed_prg_fields:
        failures.append("prg_composed_field_leak")
    profile_mismatch = {}
    for key, expected in expected_profile.items():
        actual = candidate.get(key, False if key == "cem_smooth_enabled" else None)
        if actual != expected:
            profile_mismatch[key] = {
                "actual": actual,
                "expected": expected,
            }
    if profile_mismatch:
        failures.append("e167a_profile_mismatch")
    if candidate.get("cem_smooth_enabled", False):
        failures.append("b1_cem_smooth_enabled")
    return {
        "case_id": row["case_id"],
        "override_id": output.stem,
        "override_path": C.rel(output),
        "override_sha256": C.sha256(output),
        "source_override_id": row["dcv3_override_id"],
        "source_scene_name": source.get("scene_name", ""),
        "candidate_scene_name": candidate.get("scene_name", ""),
        "e167a_profile_fields_checked": len(expected_profile),
        "e167a_profile_mismatch_json": json.dumps(
            profile_mismatch, sort_keys=True
        ),
        "non_scene_drift_json": json.dumps(drift, sort_keys=True),
        "prg_override_fields_json": json.dumps(
            leaked_override_fields
        ),
        "prg_composed_fields_json": json.dumps(
            composed_prg_fields
        ),
        "audit_status": "pass" if not failures else "fail",
        "failures": ";".join(failures),
    }


def lowerbody_object_pairs(root: ET.Element) -> list[dict[str, str]]:
    lower = {
        "left_hip_collision",
        "right_hip_collision",
        "left_thigh_collision",
        "right_thigh_collision",
        "left_shin_collision",
        "right_shin_collision",
        "left_linkage_brace_collision",
        "right_linkage_brace_collision",
        "lf0",
        "lf1",
        "lf2",
        "lf3",
        "rf0",
        "rf1",
        "rf2",
        "rf3",
    }
    leaked = []
    for pair in root.findall("./contact/pair"):
        geom1, geom2 = pair.get("geom1", ""), pair.get("geom2", "")
        if (
            geom1 == "object_collision" and geom2 in lower
        ) or (
            geom2 == "object_collision" and geom1 in lower
        ):
            leaked.append(dict(pair.attrib))
    return leaked


def build_scene(
    row: dict[str, str], *, snapshot: bool
) -> dict[str, Any]:
    base = C.repo_path(row["base_scene_act"])
    pristine = C.repo_path(row["pristine_scene_snapshot"])
    if C.sha256(base) != row["pristine_scene_snapshot_sha256"]:
        raise ValueError(
            f"{row['case_id']} restored base scene SHA drift"
        )
    if semantic_xml(base) != semantic_xml(pristine):
        raise ValueError(
            f"{row['case_id']} base scene differs from E173 pristine"
        )
    task_dir = base.parent
    staging = (
        C.RESULTS
        / "s5_handoff/config_scene_audit/hand_collision_scenes"
        / row["case_id"]
    )
    adapter = patch_scene(
        base_scene_act=base,
        out_dir=staging,
        case_id=row["case_id"],
        hand_collision_variant_id=C.HAND_COLLISION_VARIANT,
        scene_name=C.SCENE_NAME,
        install_dir=task_dir,
        repo=C.REPO,
    )
    installed = task_dir / f"{C.SCENE_NAME}.xml"
    e173_preprg = (
        C.E173_RESULTS
        / "scene_snapshot/cem_sidecars"
        / row["case_id"]
        / "scene_act_E173_rubberHull.xml"
    )
    preprg_semantic_exact = bool(
        e173_preprg.is_file()
        and semantic_xml(installed) == semantic_xml(e173_preprg)
    )
    root = ET.parse(installed).getroot()
    leaked_pairs = lowerbody_object_pairs(root)
    leaked_prefixed_pairs = [
        dict(pair.attrib)
        for pair in root.findall("./contact/pair")
        if pair.get("name", "").startswith(("E170_", "E173_"))
    ]
    model = mujoco.MjModel.from_xml_path(str(installed))
    hand_types = {}
    for name in ("lh", "rh"):
        geom_id = mujoco.mj_name2id(
            model, mujoco.mjtObj.mjOBJ_GEOM, name
        )
        hand_types[name] = (
            mujoco.mjtGeom(int(model.geom_type[geom_id])).name
            if geom_id >= 0
            else "missing"
        )
    failures = []
    if not preprg_semantic_exact:
        failures.append("not_equal_to_e173_preprg_rubber")
    if leaked_pairs:
        failures.append("lowerbody_object_pair_leak")
    if leaked_prefixed_pairs:
        failures.append("e170_e173_pair_prefix_leak")
    if set(hand_types.values()) != {"mjGEOM_MESH"}:
        failures.append("rubber_hand_not_mesh")
    if snapshot:
        source_dir = (
            C.RESULTS
            / "scene_snapshot/source_scenes"
            / row["case_id"]
        )
        sidecar_dir = (
            C.RESULTS
            / "scene_snapshot/e179_rubber_hull_sidecars"
            / row["case_id"]
        )
        source_dir.mkdir(parents=True, exist_ok=True)
        sidecar_dir.mkdir(parents=True, exist_ok=True)
        for source in (
            task_dir / "scene.xml",
            task_dir / "scene_act.xml",
            task_dir / "scene_act_meta.json",
            task_dir / "task_info.json",
        ):
            if source.is_file():
                shutil.copy2(source, source_dir / source.name)
        shutil.copy2(installed, sidecar_dir / installed.name)
    return {
        "case_id": row["case_id"],
        "base_scene_act": C.rel(base),
        "base_scene_sha256": C.sha256(base),
        "e173_preprg_rubber_scene": C.rel(e173_preprg),
        "e173_preprg_semantic_exact": preprg_semantic_exact,
        "effective_scene_act": C.rel(installed),
        "effective_scene_sha256": C.sha256(installed),
        "lh_geom_type": hand_types["lh"],
        "rh_geom_type": hand_types["rh"],
        "lowerbody_object_pair_count": len(leaked_pairs),
        "lowerbody_object_pairs_json": json.dumps(
            leaked_pairs, sort_keys=True
        ),
        "e170_e173_prefixed_pair_count": len(
            leaked_prefixed_pairs
        ),
        "adapter_ref": C.rel(
            staging / f"{C.SCENE_NAME}.xml"
        ),
        "scene_audit_status": "pass" if not failures else "fail",
        "failures": ";".join(failures),
    }


