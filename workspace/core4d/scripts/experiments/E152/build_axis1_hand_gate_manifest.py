def rel(path: str | Path) -> str:
    if not path:
        return ""
    p = Path(path)
    try:
        return str(p.resolve().relative_to(REPO.resolve()))
    except Exception:
        return str(path)


def repo_path(path: str | Path) -> Path:
    p = Path(path)
    return p if p.is_absolute() else REPO / p


def read_tsv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def write_tsv(path: Path, rows: list[dict[str, Any]], fields: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields, delimiter="\t", lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: "" if row.get(field) is None else row.get(field, "") for field in fields})


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def git_head() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO, text=True).strip()
    except Exception:
        return "unknown"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def result_paths(variant: str) -> tuple[str, str, str]:
    return (
        rel(CEM_ROOT / f"{variant}.npz"),
        rel(CEM_ROOT / f"{variant}_outdir_full/trajectory_mjwp_act.npz"),
        rel(CEM_ROOT / f"{variant}_full.mp4"),
    )


def split_for(short: str) -> str:
    if short == "box021_029_p2":
        return "local-gpu0"
    if short == "box004_083_p2":
        return "remote-gpu0"
    if short == "box023_person2":
        return "remote-gpu1"
    raise ValueError(short)


def write_override(
    row: dict[str, Any],
    *,
    base_override: str,
    hand_gate_min_sdf_m: float,
    hand_gate_max_violation_pct: float,
) -> str:
    path = OVERRIDE_ROOT / f"core4d_{row['variant']}.yaml"
    base_stem = Path(base_override).stem
    lines = [
        "# @package _global_",
        "# Auto-generated by workspace/core4d/scripts/E152/build_axis1_hand_gate_manifest.py.",
        f"# E152 hand-object gate method={row['method']} case={row['short_case_id']}.",
        "defaults:",
        f"  - {base_stem}",
        "  - _self_",
        "",
        f"task: {row['derived_task']}",
        f"scene_name: {row['scene_name']}",
        "video_camera: auto",
        "",
        "cem_hand_gate_enabled: true",
        'cem_hand_gate_geom_names: ["lh", "rh"]',
        "cem_hand_gate_geom_ids: []",
        f"cem_hand_gate_min_sdf_m: {hand_gate_min_sdf_m:.6f}",
        f"cem_hand_gate_max_violation_pct: {hand_gate_max_violation_pct:.6f}",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return rel(path)


def build_row(
    *,
    ordinal: int,
    method: str,
    base: dict[str, str],
    baseline: dict[str, str],
    b1: dict[str, str],
    hand_gate_min_sdf_m: float,
    hand_gate_max_violation_pct: float,
) -> dict[str, Any]:
    short = baseline["short_case_id"]
    variant = f"E152_{short}_{method}"
    use_gate = method in {"gateA", "gateA_b1"}
    if method == "baseline":
        run_status = "reuse_baseline"
        source_exp = baseline["source_exp"]
        split = "reuse"
        method_group = "baseline"
        compare_to_method = ""
        result_npz, outdir_npz, video = baseline["result_npz"], baseline["outdir_npz"], baseline["video"]
        override = baseline["override"]
        hand_support_scale = "0.0"
    elif method == "b1":
        run_status = "reuse_e151_b1"
        source_exp = "E151"
        split = "reuse"
        method_group = "B1"
        compare_to_method = "baseline"
        result_npz, outdir_npz, video = b1["result_npz"], b1["outdir_npz"], b1["video"]
        override = b1["override"]
        hand_support_scale = b1["hand_support_scale"]
    else:
        run_status = "to_run"
        source_exp = "E152"
        split = split_for(short)
        method_group = "gateA" if method == "gateA" else "gateA+B1"
        compare_to_method = "baseline" if method == "gateA" else "b1"
        result_npz, outdir_npz, video = result_paths(variant)
        hand_support_scale = "0.0" if method == "gateA" else b1["hand_support_scale"]
        override = ""
    row: dict[str, Any] = {
        "ordinal": ordinal,
        "variant": variant,
        "short_case_id": short,
        "method": method,
        "method_group": method_group,
        "compare_to_method": compare_to_method,
        "e151_baseline_variant": baseline["variant"],
        "e151_b1_variant": b1["variant"],
        "e148_variant": baseline["e148_variant"],
        "e109_case_id": baseline["e109_case_id"],
        "case_id": baseline["case_id"],
        "object_key": baseline["object_key"],
        "object_category": baseline["object_category"],
        "person_idx": baseline["person_idx"],
        "split": split,
        "run_status": run_status,
        "source_exp": source_exp,
        "target_variant_id": method,
        "target_npz": base.get("target_npz", ""),
        "target_clean_max_diff_m": base.get("target_clean_max_diff_m", ""),
        "target_clean_selected": base.get("target_clean_selected", ""),
        "hand_support_scale": hand_support_scale,
        "cem_hand_gate_enabled": "true" if use_gate else "false",
        "cem_hand_gate_min_sdf_m": f"{hand_gate_min_sdf_m:.6f}" if use_gate else "",
        "cem_hand_gate_max_violation_pct": f"{hand_gate_max_violation_pct:.6f}" if use_gate else "",
        "hand_collision_variant_id": "rubber_hull",
        "derived_task": baseline["derived_task"],
        "target_scene": baseline["target_scene"],
        "trajectory": baseline["trajectory"],
        "base_scene_act": baseline["base_scene_act"],
        "rubber_scene_act": baseline["rubber_scene_act"],
        "scene_name": baseline["scene_name"],
        "override": override,
        "object_asset": baseline["object_asset"],
        "mask_path": baseline["mask_path"],
        "baseline_variant": baseline["variant"],
        "baseline_npz": baseline["result_npz"],
        "baseline_outdir_npz": baseline["outdir_npz"],
        "baseline_video": baseline["video"],
        "b1_variant": b1["variant"],
        "b1_npz": b1["result_npz"],
        "b1_outdir_npz": b1["outdir_npz"],
        "b1_video": b1["video"],
        "result_npz": result_npz,
        "outdir_npz": outdir_npz,
        "video": video,
        "expected_quality": baseline["expected_quality"],
        "remote_sync_key": baseline["remote_sync_key"],
    }
    if use_gate:
        base_override = baseline["override"] if method == "gateA" else b1["override"]
        row["override"] = write_override(
            row,
            base_override=base_override,
            hand_gate_min_sdf_m=hand_gate_min_sdf_m,
            hand_gate_max_violation_pct=hand_gate_max_violation_pct,
        )
    return row


def copy_scene_snapshot(rows: list[dict[str, Any]]) -> None:
    snap_root = RESULT_ROOT / "scene_snapshot"
    snap_root.mkdir(parents=True, exist_ok=True)
    unique: dict[str, dict[str, Any]] = {}
    for row in rows:
        unique.setdefault(row["derived_task"], row)
    lines = [
        "# E152 scene snapshot",
        f"# Git HEAD: {git_head()}",
        "",
        "task\tfile\tsha256\tpath",
    ]
    for task, row in sorted(unique.items()):
        dst_dir = snap_root / task
        dst_dir.mkdir(parents=True, exist_ok=True)
        candidates = [
            repo_path(row["target_scene"]),
            repo_path(row["base_scene_act"]),
            repo_path(row["rubber_scene_act"]),
            repo_path(row["base_scene_act"]).parent / "scene_act_meta.json",
            repo_path(row["base_scene_act"]).parent / "task_info.json",
        ]
        seen: set[Path] = set()
        for src in candidates:
            if src in seen or not src.is_file():
                continue
            seen.add(src)
            dst = dst_dir / src.name
            shutil.copy2(src, dst)
            lines.append(f"{task}\t{src.name}\t{sha256(src)}\t{rel(dst)}")
    (snap_root / "manifest.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")


def validate(rows: list[dict[str, Any]]) -> None:
    if len(rows) != 12:
        raise SystemExit(f"E152 expected 12 rows, got {len(rows)}")
    todo = [row for row in rows if row["run_status"] == "to_run"]
    if len(todo) != 6:
        raise SystemExit(f"E152 expected to_run=6, got {len(todo)}")
    split_counts: dict[str, int] = {}
    for row in todo:
        split_counts[row["split"]] = split_counts.get(row["split"], 0) + 1
    if split_counts != {"local-gpu0": 2, "remote-gpu0": 2, "remote-gpu1": 2}:
        raise SystemExit(f"E152 expected split 2/2/2, got {split_counts}")
    missing = []
    for row in rows:
        for key in ("override", "target_scene", "trajectory", "base_scene_act", "rubber_scene_act", "object_asset", "mask_path"):
            if row.get(key) and not repo_path(row[key]).is_file():
                missing.append(f"{row['variant']}:{key}:{row[key]}")
        if row["run_status"] != "to_run":
            if not repo_path(row["outdir_npz"]).is_file():
                missing.append(f"{row['variant']}:outdir_npz:{row['outdir_npz']}")
            if not repo_path(row["result_npz"]).is_file():
                missing.append(f"{row['variant']}:result_npz:{row['result_npz']}")
    if missing:
        raise SystemExit("E152 manifest missing/invalid files:\n" + "\n".join(missing))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--hand-gate-min-sdf-m", type=float, default=-0.010)
    parser.add_argument("--hand-gate-max-violation-pct", type=float, default=0.05)
    args = parser.parse_args()

    e151_rows = read_tsv(E151_VARIANTS)
    by_case_method = {(row["short_case_id"], row["method"]): row for row in e151_rows}
    rows: list[dict[str, Any]] = []
    ordinal = 1
    for short in CASES:
        baseline = by_case_method[(short, "baseline")]
        b1 = by_case_method[(short, "b1_mesh")]
        for method in METHODS:
            base = baseline if method in {"baseline", "gateA"} else b1
            rows.append(
                build_row(
                    ordinal=ordinal,
                    method=method,
                    base=base,
                    baseline=baseline,
                    b1=b1,
                    hand_gate_min_sdf_m=args.hand_gate_min_sdf_m,
                    hand_gate_max_violation_pct=args.hand_gate_max_violation_pct,
                )
            )
            ordinal += 1
    validate(rows)
    SCRIPT_ROOT.mkdir(parents=True, exist_ok=True)
    write_tsv(SCRIPT_ROOT / "variants.tsv", rows, FIELDS)
    write_tsv(RESULT_ROOT / "cases_manifest.tsv", rows, FIELDS)
    copy_scene_snapshot(rows)
    write_json(
        RESULT_ROOT / "manifest_summary.json",
        {
            "rows": len(rows),
            "reuse": 6,
            "to_run": 6,
            "cases": CASES,
            "methods": METHODS,
            "split": {"local-gpu0": 2, "remote-gpu0": 2, "remote-gpu1": 2},
            "cem_hand_gate_min_sdf_m": args.hand_gate_min_sdf_m,
            "cem_hand_gate_max_violation_pct": args.hand_gate_max_violation_pct,
            "git_head": git_head(),
        },
    )
    print(f"wrote {rel(SCRIPT_ROOT / 'variants.tsv')}")
    print("rows=12 reuse=6 to_run=6 local-gpu0=2 remote-gpu0=2 remote-gpu1=2")


if __name__ == "__main__":
    main()
