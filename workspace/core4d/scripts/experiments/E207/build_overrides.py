#!/usr/bin/env python3
"""Write + audit the 9 Hydra override YAMLs for E207 (G1only).

Each override inherits the E178 contactAlignedTop config verbatim and changes
exactly one key -- ``scene_name`` -> the G1 gravcomp sidecar. The A2 hand-gate
that E205 applies is deliberately NOT applied, so the hand-gate stays at its
E163 default (A0).

The audit is stronger than a spot-check: it composes both the E178 baseline and
the E207 candidate through Hydra and diffs every resolved key, requiring the
symmetric difference to be exactly {"scene_name"}. That is what makes the
"single variable vs E178" claim checkable rather than asserted.

Usage:
    .venv/bin/python workspace/core4d/scripts/experiments/E207/build_overrides.py
    ... --no-audit
    ... --limit N
"""

from __future__ import annotations

import argparse
from typing import Any

import e207_common as C

HEADER = "# @package _global_\n# Auto-generated by E207/build_overrides.py.\n"

#: Keys allowed to differ between the composed E178 and E207 configs.
ALLOWED_DIFF = {"scene_name"}


def write_override(case_id: str) -> None:
    body = (
        f"{HEADER}"
        "# E207 G1only (E178 PRG + G1 object gravcomp, A0 hand-gate) arm.\n"
        "# Single variable vs E178: scene_name -> gravcomp sidecar. No A2 retune.\n"
        "defaults:\n"
        f"- {C.e178_override_id(case_id)}\n"
        "- _self_\n"
        f"scene_name: {C.SCENE}\n"
    )
    C.override_path(case_id).write_text(body, encoding="utf-8")


def _compose(override_id: str) -> dict[str, Any]:
    from hydra import compose, initialize_config_dir
    from omegaconf import OmegaConf

    config_dir = str((C.REPO / "examples/config").resolve())
    with initialize_config_dir(version_base=None, config_dir=config_dir):
        cfg = compose(config_name="default", overrides=[f"+override={override_id}"])
    out = OmegaConf.to_container(cfg, resolve=True)
    assert isinstance(out, dict)
    return out


def audit_case(case_id: str) -> list[str]:
    base = _compose(C.e178_override_id(case_id))
    cand = _compose(C.override_id(case_id))
    fails: list[str] = []

    drift = {
        key
        for key in set(base) | set(cand)
        if base.get(key, "\0missing") != cand.get(key, "\0missing")
    }
    unexpected = drift - ALLOWED_DIFF
    if unexpected:
        fails.append(
            "non_axis_drift:" + ",".join(f"{k}({base.get(k)}->{cand.get(k)})" for k in sorted(unexpected))
        )
    if "scene_name" not in drift:
        fails.append("scene_name did not change vs E178")
    if cand.get("scene_name") != C.SCENE:
        fails.append(f"scene_name={cand.get('scene_name')}!={C.SCENE}")

    # A0: the hand gate must remain at the E163 default (this is what separates
    # E207 from E205 -- getting it wrong silently turns E207 into G1A2).
    for key, want in C.E163_HAND_GATE.items():
        got = cand.get(key)
        if got is None or abs(float(got) - want) > 1e-9:
            fails.append(f"{key}={got}!=E163_default({want})")

    # PRG must still be on (E207 is E178 + gravcomp, not noPRG).
    if float(cand.get("leg_object_penalty_scale", 0.0)) != 2.0:
        fails.append(f"PRG leg_object_penalty_scale={cand.get('leg_object_penalty_scale')}!=2.0")
    if not bool(cand.get("cem_leg_gate_enabled", False)):
        fails.append("PRG cem_leg_gate_enabled!=true")
    if cand.get("object_collision_sdf_mode") != "union":
        fails.append(f"object_collision_sdf_mode={cand.get('object_collision_sdf_mode')}")
    return fails


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--audit", action="store_true", default=True)
    ap.add_argument("--no-audit", dest="audit", action="store_false")
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()

    cases = list(C.CASES)[: args.limit] if args.limit else list(C.CASES)
    for case_id in cases:
        write_override(case_id)
    print(f"wrote {len(cases)} override YAMLs to {C.OVERRIDE_DIR.relative_to(C.REPO)}")

    if not args.audit:
        return 0
    failures = {}
    for case_id in cases:
        fails = audit_case(case_id)
        if fails:
            failures[C.override_id(case_id)] = fails
    if failures:
        for override, fails in failures.items():
            print(f"  FAIL {override}: {'; '.join(fails)}")
        raise SystemExit(f"override audit FAILED for {len(failures)} configs")
    print(
        f"audit PASS: {len(cases)} overrides differ from E178 by exactly "
        f"{sorted(ALLOWED_DIFF)}; hand-gate == E163 default (A0); PRG on"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
