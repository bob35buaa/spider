#!/usr/bin/env python3
"""E214 four-ablation LaTeX table (booktabs) -- Overall, 50 cases, WITH @10mm rows.

Non-destructive companion to build_ablation_table_50.py: reads the same
results/E214/reports/e214_ablation_overall.tsv and emits a NEW file
ablation_table_50_10mm.tex (the hand-polished ablation_table_50.tex is left intact).

Adds Phys. contact@10mm and Phys. penetration@10mm alongside the @5mm rows, and
marks best (bold) / second-best (underline) per row, direction-aware.

Column -> series map (friendly names match the paper's hand-edited table):
  Ours              = full
  w/o local reward  = A1_contactHDMI_only   (-SB, surface-band / fine SDF removed)
  w/o global reward = A2_surfaceBand_only   (-HDMI, coarse anchor removed)
  w/o hard select   = A3_softPenalty_only   (-gate, hard candidate gates removed)
  w/o soft penalty  = A4_hardGate_only       (-pen, soft penalties removed)
"""

from __future__ import annotations

import csv
from pathlib import Path

REPO = Path(__file__).resolve().parents[5]
TSV = REPO / "workspace/core4d/results/E214/reports/e214_ablation_overall.tsv"
OUT = Path(__file__).resolve().parent / "ablation_table_50_10mm.tex"

SERIES = ["full", "A1_contactHDMI_only", "A2_surfaceBand_only",
          "A3_softPenalty_only", "A4_hardGate_only"]
COLS = ["Ours", "w/o local reward", "w/o global reward", "w/o hard select", "w/o soft penalty"]

# metric_key, label, arrow (+ = higher better, - = lower better), kind, group-break-before
ROWS = [
    ("contact_5mm",   r"Phys. contact@5mm ($\%$)",   "+", "pct", False),
    ("contact_10mm",  r"Phys. contact@10mm ($\%$)",  "+", "pct", False),
    ("pen_5mm",       r"Phys. penetration@5mm ($\%$)",  "-", "pct", False),
    ("pen_10mm",      r"Phys. penetration@10mm ($\%$)", "-", "pct", False),
    ("pen_max_mm",    r"Max phys penetration (mm)",  "-", "mm",  False),
    ("track_mpjpe_g", r"MPJPE-G (cm)",               "-", "cm",  True),
    ("track_mpjpe_l", r"MPJPE-L (cm)",               "-", "cm",  False),
    ("track_obj_pos", r"Obj pos err (cm)",           "-", "cm",  True),
    ("track_obj_ori", r"Obj ori err (deg)",          "-", "deg", False),
]


def load() -> dict[tuple[str, str], float]:
    out: dict[tuple[str, str], float] = {}
    with TSV.open() as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            if r["mean"] != "":
                out[(r["metric"], r["series"])] = float(r["mean"])
    return out


def fmt(mean: float, kind: str) -> str:
    if kind == "pct":
        return f"{mean * 100:.1f}"
    if kind in ("cm", "deg"):
        return f"{mean:.2f}"
    if kind == "mm":
        return f"{mean:.1f}"
    return f"{mean:.3g}"


def rank(vals: dict[str, float], arrow: str) -> tuple[str | None, str | None]:
    """(best_series, second_series) direction-aware."""
    items = sorted(vals.items(), key=lambda kv: kv[1], reverse=(arrow == "+"))
    best = items[0][0] if items else None
    second = items[1][0] if len(items) > 1 else None
    return best, second


def main() -> int:
    data = load()
    lines = [
        r"% Auto-generated by build_ablation_table_50_10mm.py -- E214 four-ablation (Overall, 50 cases, +@10mm).",
        r"% Requires: \usepackage{booktabs}.",
        r"",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Leave-one-out ablation of the two core contributions on "
        r"CORE4D-G1 (all 50 paper sequences). Each ablation removes one "
        r"sub-component and re-runs the sampling-based MPC; \textbf{Ours} is the "
        r"full method. \emph{Contribution 1 (Multi-Scale Contact)}: w/o local "
        r"reward removes the fine SDF surface-band term, w/o global reward removes "
        r"the coarse anchor-attraction term. \emph{Contribution 2 (Part-wise "
        r"Penetration)}: w/o hard select removes all hard candidate gates, w/o "
        r"soft penalty removes all soft penetration penalties. Physical contact / "
        r"penetration are reported at both 5\,mm and 10\,mm bands; MPJPE is the "
        r"whole-body mean per-joint Cartesian error (MPJPE-G global, MPJPE-L "
        r"pelvis-aligned). $\uparrow$/$\downarrow$: higher/lower is better; "
        r"\textbf{bold} = best, \underline{underline} = second best. Note w/o "
        r"global reward's lower penetration is an artifact of failing to reach the "
        r"object (see MPJPE-G), not better contact.}",
        r"\label{tab:ablation50_10mm}",
        r"\begin{tabular}{l ccccc}",
        r"\toprule",
        "Metric & " + " & ".join(COLS) + r" \\",
        r"\midrule",
    ]
    for metric, label, arrow, kind, brk in ROWS:
        if brk:
            lines.append(r"\midrule")
        vals = {s: data[(metric, s)] for s in SERIES if (metric, s) in data}
        best, second = rank(vals, arrow)
        cells = []
        for s in SERIES:
            if s not in vals:
                cells.append("--")
                continue
            txt = fmt(vals[s], kind)
            if s == best:
                txt = rf"\textbf{{{txt}}}"
            elif s == second:
                txt = rf"\underline{{{txt}}}"
            cells.append(txt)
        arr = r"\uparrow" if arrow == "+" else r"\downarrow"
        lines.append(rf"{label} ${arr}$ & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")

    standalone = OUT.with_name("ablation_table_50_10mm_standalone.tex")
    standalone.write_text(
        "\\documentclass{article}\n"
        "\\usepackage[margin=0.4in,landscape,a2paper]{geometry}\n"
        "\\usepackage{booktabs}\n\\usepackage{graphicx}\n\\pagestyle{empty}\n"
        "\\begin{document}\n\\input{ablation_table_50_10mm.tex}\n\\end{document}\n",
        encoding="utf-8",
    )
    print(f"wrote {standalone.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
